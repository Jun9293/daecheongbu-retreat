# -*- coding: utf-8 -*-
"""넘김 목록을 **읽는 곳은 여기 하나다** (11-3 3단계).

세 검사(`check_stale` · `check_named` · `check_names`)가 저마다 같은
모양(`무엇 | 왜 넘기는가`)을 읽고 있었다. 셋 다 **이유 칸이 비면 그 줄을
조용히 버렸다** — 즉 이유를 안 적으면 넘김이 안 되는 것이 아니라,
**넘김도 안 되고 아무 말도 안 나왔다.**

## 왜 이유를 강제하는가

넘김 목록은 **줄어들 일이 없습니다.** 자라기만 하는 목록은 사람이 읽지
않게 되고, 그러면 「거기 적어 두면 통과」 가 되어 검사가 있으나 마나
해집니다 (4-11 의 그 자리). 막을 수 있는 것은 하나뿐입니다 — **왜
넘기는지를 반드시 적게 하는 것.** 이유를 적으려면 그 줄을 한 번은
생각해야 하고, 생각하면 「이건 문서를 고치는 게 맞네」 가 걸러집니다.

`check_dev_db.제외칸` 이 이미 그렇게 하고 있습니다(칸마다 근거를 적음).
여기서 배운 것을 파일 쪽 목록에도 옮깁니다.

## 규칙

- `#` 로 시작하는 줄과 빈 줄은 주석
- 나머지는 `무엇 | 왜 넘기는가` — **이유 칸을 채워야 넘김이 된다**
- **이유가 넘기는 그 말을 다시 쓰면 통과가 아니다** (아래)

## 이유가 그 말을 인용하면 꼬리를 문다

어떤 말을 금지하는 도구는 **그것을 설명하려고 스스로 담게 됩니다**
(10장). 넘김의 이유 칸이 바로 그 자리입니다 — 넘기는 말을 이유에 그대로
적으면 **그 줄이 다시 걸려 또 넘김이 필요해집니다.** 2026-09-08 에 실제로
한 바퀴 돌았습니다: 세는 말 검사가 자기 시험을 잡아 넘겼더니, 그 넘김 줄이
같은 말을 담아 또 걸렸습니다.

그래서 **예시 없이 씁니다.** 「확장자를 가리킨 말이지 선택자가 아니다」 로
충분하고, 그 확장자를 다시 적을 이유가 없습니다.

**이유의 `근거:` 뒤는 보지 않습니다** — 그건 인용이 아니라 **가리키는
자리**이고, 파일 경로에 그 이름이 들어가는 것은 오히려 맞는 모양입니다.

**문턱을 두지 않습니다.** 「두 글자 이상」 같은 것을 넣으면 `-` 가 `x`
가 되고 `x` 가 `TODO` 가 됩니다 — 자리표시자를 막는 규칙은 자리표시자를
길게 만들 뿐입니다. 실제 문지기는 **사람이 그 칸을 쓴다는 것**과
**커밋 전 검토가 그 줄을 읽는다는 것**이고, 이 검사가 하는 일은 「빈
채로 지나가는 것」 을 막는 데까지입니다.

그래서 `〃`(바로 위와 같다) 도 통과합니다 — 같은 이유를 열 줄에 베껴
적게 하면 그게 더 안 읽힙니다.

## 한계

**빈 자리는 막고 거짓은 사람이 본다.** 이유가 **있는지**만 재고 **맞는지**는 안 잰다 — 아무 말이나 적으면 통과한다. 그 이상은 기계가 못 가르므로 커밋 전 검토가 그 줄을 읽는다.
"""

from __future__ import annotations

import pathlib


def 인용했나(무엇: str, 이유: str) -> bool:
    """이유가 넘기는 그 말을 다시 썼는가 (위 독스트링).

    파일 경로는 **이름만 적어도 인용**이다 — `docs/옛말.md` 를 넘기며
    이유에 `옛말.md` 라고 쓰면 같은 말을 되풀이한 것이다.

    `근거:` 뒤는 보지 않는다. 그건 인용이 아니라 **가리키는 자리**다.
    """
    본문 = 이유.split("근거:")[0]
    이름 = 무엇.rstrip("/").rsplit("/", 1)[-1]
    return bool(이름) and (무엇 in 본문 or 이름 in 본문)


def 읽는다(경로: pathlib.Path) -> tuple[set[str], list[tuple[int, str]]]:
    """(넘길 것, 안 되는 줄) — 안 되는 줄은 넘기지 **않는다.**

    안 되는 줄은 둘이다 — **이유가 빈 줄**과 **이유가 그 말을 다시 쓴
    줄.** 버리지 않고 돌려주는 이유는, 부르는 쪽이 그것을 **실패로 낼 수
    있게** 하기 위해서다. 조용히 버리면 적은 사람은 넘긴 줄 알고, 검사는
    안 넘긴 채로 돌아 서로 다른 것을 믿는다.
    """
    if not 경로.exists():
        return set(), []
    나온것: set[str] = set()
    안되는줄: list[tuple[int, str]] = []
    for 번호, 줄 in enumerate(경로.read_text(encoding="utf-8").splitlines(), 1):
        t = 줄.strip()
        if not t or t.startswith("#"):
            continue
        칸 = [x.strip() for x in t.split("|")]
        if not (len(칸) >= 2 and 칸[0] and 칸[1]):
            안되는줄.append((번호, t))
        elif 인용했나(칸[0], 칸[1]):
            안되는줄.append((번호, t))
        else:
            나온것.add(칸[0])
    return 나온것, 안되는줄


def 말한다(경로: pathlib.Path, 안되는줄: list[tuple[int, str]]) -> None:
    """안 되는 줄을 사람 말로 낸다 — 부르는 쪽은 0 이 아닌 값으로 끝난다."""
    print()
    print(f"!! {경로.name} 에 넘김이 안 되는 줄이 {len(안되는줄)}개 있습니다.")
    print("   `무엇 | 왜 넘기는가` 로 적으세요 — 이유 없는 넘김은")
    print("   목록만 늘리고, 늘어난 목록은 아무도 읽지 않습니다.")
    print("   그리고 **이유에 그 말을 다시 쓰지 마세요** — 그 줄이 다시")
    print("   걸려 또 넘김이 필요해집니다 (예시 없이 씁니다).")
    for 번호, 줄 in 안되는줄:
        print(f"    {번호:>4}줄  {줄[:70]}")
