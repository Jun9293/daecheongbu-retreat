def 회의별대조(묶음) -> list[dict]:
    """성적표가 적어 둔 회의별 수와 이번에 낸 것을 **회의마다** 견준다.

    합계 하나로 막으면 한 회의가 어긋났을 때 나머지까지 못 쓴다.
    대조는 회의 단위로 하는 것이므로 어긋난 회의만 빼면 된다.
    """
    나온것 = []
    for m, r in 묶음:
        논의 = sum(1 for x in r.제안들 if x.kind == "discussion")
        새것 = sum(1 for x in r.제안들 if x.kind == "new")
        적힌것 = 일판회의별.get(m.title)
        나온것.append({"제목": m.title, "성적표": 적힌것, "이번": (논의, 새것),
                    "같나": 적힌것 == (논의, 새것)})
    return 나온것


def 이름(x) -> str:
    """**run 번호까지 붙인다.** 이름이 비슷한 다른 업무가 있다 —
    07.05 에서 1판은 「방명록 디자인 완료」(run 78), 2판은 「방명록」(run 29)
    을 냈다. 이름만 보면 같은 것으로 읽힌다.
    """
    if x.kind == "discussion":
        return f"「{x.run_title}」 (run {x.run_id})"
    return (x.title or x.text or "").strip()


def 도출(묶음, 대조: list[dict]) -> dict:
    """성적표의 **X 일곱**에서 나머지를 O 로 도출한다.

    사람이 O 를 하나하나 적은 것이 아니라 **X 를 뺀 나머지**다. 그래서
    화면에도 문서에도 `(도출)` 을 붙인다 — 사람이 적은 것과 섞이면
    나중에 무엇이 근거였는지 알 수 없다.

    자리를 맞출 수 없는 회의(낸 개수가 09-03 과 다른 회의)는 **비워 둔다.**
    번호가 몇 번째를 가리키는지 알 수 없기 때문이다.
    """
    같나 = {x["제목"]: x["같나"] for x in 대조}
    판정 = {}          # (회의 제목, 순번) -> "O(도출)" | "X(도출)"
    맞힌것 = []        # 대조 칸에 낼 것
    셈 = {}
    for m, r in 묶음:
        제안들 = [x for x in r.제안들 if x.kind in 제안종류]
        X번호 = 일판X.get(m.title, ())
        셈[m.title] = {"낸것": len(제안들), "X": 0, "O": 0,
                      "맞출수있나": 같나.get(m.title, False)}
        if not 같나.get(m.title):
            continue
        for i, x in enumerate(제안들, 1):
            if i in X번호:
                판정[(m.title, i)] = "X(도출)"
                셈[m.title]["X"] += 1
            else:
                판정[(m.title, i)] = "O(도출)"
                셈[m.title]["O"] += 1
                맞힌것.append((m.title, 제안종류[x.kind], 이름(x)))
    return {"판정": 판정, "맞힌것": 맞힌것, "셈": 셈}


