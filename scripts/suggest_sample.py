        묶음 = []
        총원 = 0.0
        for 제목 in 표본:
            m = db.scalars(
                select(Meeting).where(Meeting.retreat_id == retreat.id,
                                      Meeting.title == 제목)).first()
            if m is None:
                print(f"  ! 회의록 없음: {제목}")
