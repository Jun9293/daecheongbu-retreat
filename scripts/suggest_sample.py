                # 냈는지 지금 다시 적을 수 있다
                r = S.결과(제안들=S.낱말제안(db, retreat=retreat, meeting=m,
                                        as_of=m.meeting_date),
                          방식="낱말", 말="낱말 겹침으로 골랐습니다")
