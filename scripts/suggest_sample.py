def 공개본(원본: pathlib.Path) -> int:
    """**익명화한 사본을 `docs/review/` 에 쓴다.**

    바꾸는 로직을 여기 새로 쓰지 않고 `scripts/anonymize.py` 의 함수를
    부른다 — 두 벌이 되면 한쪽만 고쳐지고, 갈린 쪽이 실명을 흘린다.

    바꾼 개수를 돌려준다. **0이면 그 사실도 말한다** — 원래 없었던 것과
    못 찾은 것이 같은 모양이면 안 된다.
    """
    import importlib.util
    스펙 = importlib.util.spec_from_file_location(
        "_anonymize_for_public", _뿌리 / "scripts" / "anonymize.py")
    A = importlib.util.module_from_spec(스펙)
    스펙.loader.exec_module(A)
    갈곳 = 공개곳.get(원본.name)
    if 갈곳 is None:
        print(f"   공개할 자리를 모르는 파일입니다: {원본.name}")
        print("   `--out` 으로 낸 것은 공개본을 만들지 않습니다.")
        return -1
    새글, 바뀐수 = A.swap(원본.read_text(encoding="utf-8"), doc=True)
    갈곳.write_text(새글, encoding="utf-8")
    return 바뀐수


