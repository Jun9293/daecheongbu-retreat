r"""검토용 보고에 **지시문 대조 표**가 있는지 본다 (11-3 · 2026-09-12).

## 왜 검사인가

지금 보는 눈이 셋인데 **셋 다 「지시문에 있는데 안 한 것」 을 못 봅니다** —
pytest 는 함수를 부르고, 검토자는 코드를 읽고, 글검사는 글자를 봅니다.
시킨 것을 빠뜨려도 그 셋은 전부 초록입니다. 실제로 보고에 와서야 드러난
적이 여러 번이고, 그때는 이미 커밋한 뒤였습니다.

그래서 **판을 마치기 전에 지시문 항목을 하나하나 짚어** `했다` ·
`안 했다` · `다르게 했다` 를 적습니다. 그 표가 있는지를 여기서 봅니다.

## 무엇을 보나 — **모양만**

- 보고에 그 표를 여는 머리가 있는가
- 그 아래에 **항목 번호가 붙은 줄**이 하나라도 있는가
- 줄마다 판정이 **셋 중 하나**인가

## 이것으로 안 닫히는 것

**항목 번호가 그 지시문과 맞는지는 못 봅니다.** 지시문은 저장소에 없습니다 —
사람이 채팅으로 주고 보고에만 옮겨 적힙니다. 그러니 **1번을 통째로 빼고
2·3 만 적어도 이 검사는 초록**입니다. 그 자리는 사람과 검토자가 봅니다
(검토자는 지시문을 함께 받으므로 실제로 볼 수 있습니다 — 덩어리와 다릅니다).

**판정이 사실인지도 못 봅니다.** 「했다」 라고 적으면 그대로 지나갑니다.
**안 보는 것을 본다고 적지 않습니다.**

    .venv\\Scripts\\python.exe scripts/check_orders.py
"""

from __future__ import annotations

import pathlib
import re
import sys

if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(errors="replace")

ROOT = pathlib.Path(__file__).resolve().parent.parent
보고 = ROOT / "docs" / "review" / "최근.md"

# 표를 여는 머리. 이 글자가 정본이고 11-3 과 보고가 받아 쓴다
머리 = "지시문 대조"
# **찍는 수와 재는 수는 같은 곳에서 나온다.** 전에는 찍을 때만 파일 전체를
# 다시 세어, 검토자 원문에 표 꼴이 섞이면 **잰 적 없는 줄까지 세어졌다**
# (2026-09-12 검토가 짚었다). `본다()` 가 센 것을 그대로 쓴다.
마지막줄수 = 0

# 판정 셋. **이것 말고는 안 받는다** — 「거의 다 했다」 같은 말이 들어오면
# 「했다」 로 읽히고, 그 자리가 정확히 안 한 것을 숨기는 자리가 된다
판정들 = ("했다", "안 했다", "다르게 했다")


def 판정인가(줄: str) -> bool:
    """그 줄의 어느 칸이 **판정으로 시작하는가.**

    **「들어 있으면」 으로 보지 않는다** — 「거의 다 했다」 에도 「했다」 가
    들어 있어서, 정확히 **안 한 것을 숨기는 말**이 통과한다. 그래서 칸을
    갈라 **머리**를 본다. 굵게 쓴 것(`**했다**`)도 같이 받는다.
    """
    for 칸 in 줄.split("|")[2:]:
        머리 = 칸.strip().lstrip("*").strip()
        if any(머리.startswith(p) for p in 판정들):
            return True
    return False

# 표의 칸 나누는 줄(`|---|---|`)
가름줄 = re.compile(r"^\|[\s|:-]+\|?\s*$")


def 항목줄인가(줄: str) -> bool:
    """그 줄이 **항목 줄**인가 — 표의 머리와 가름줄만 빼고 전부다.

    **번호 꼴로 고르지 않는다.** 전에는 `1` · `1-a` 만 받았는데, 같은 표의
    수용 기준 줄(`가)` · `바)`)이 **아예 안 보였다** — 스물다섯 줄 중 여섯이
    판정 검사를 안 지났고, 거기에 무슨 말을 써도 초록이었다. 반대로 다음
    지시문이 번호를 다르게 매기면 「표가 비었습니다」 로 빨개진다.
    **번호 매기는 법을 검사가 정하지 않는다** (2026-09-12 검토가 짚었다).
    """
    return 줄.startswith("|") and not 가름줄.match(줄)


def 표들(줄들: list[str]) -> list[list[int]]:
    """이어지는 표 줄을 묶어 낸다 — **머리와 가름줄은 빼고** 줄 번호로.

    한 장에 표가 둘일 수 있다. 실제로 이 판의 보고가 그렇다 — 「무엇을
    보나 / 못 보나」 표와 대조 표가 같은 말의 장 아래 있다.
    """
    묶음, 지금 = [], []
    for i, 줄 in enumerate(줄들):
        if not 줄.startswith("|"):
            if 지금:
                묶음.append(지금)
                지금 = []
            continue
        지금.append(i)
    if 지금:
        묶음.append(지금)

    낸다 = []
    for 표 in 묶음:
        가름 = [i for i in 표 if 가름줄.match(줄들[i])]
        뺄것 = set(가름) | {i - 1 for i in 가름}
        줄만 = [i for i in 표 if i not in 뺄것]
        if 줄만:
            낸다.append(줄만)
    return 낸다


def 본다(글: str) -> list[str]:
    """탈이 있으면 그 말들을 돌려준다 — **빈 목록이 통과다.**

    부르는 곳이 둘이다(이 파일의 `main` 과 시험) — 파일을 만들지 않고 글로
    재려고 갈라 두었다. 두 곳에서 따로 판정하면 시험이 검사와 다른 것을 본다
    (`check_handoff` · `check_placeholder` 와 같은 꼴).
    """
    global 마지막줄수
    줄들 = 글.splitlines()
    머리자리 = [i for i, 줄 in enumerate(줄들) if 줄.startswith("#") and 머리 in 줄]
    마지막줄수 = 0
    if not 머리자리:
        return [f"보고에 「{머리}」 를 여는 머리가 없습니다 — 11-3 이 넣으라고 한 표입니다"]

    # **머리가 여럿이면 전부 본다.** 보고가 그 표를 놓기 전에 같은 말로
    # 한 장을 먼저 쓸 수 있다 — 앞엣것에서 멈추면 **표가 있는데도
    # 「비었다」** 가 난다. 실제로 이 판이 그렇게 한 번 빨갰다.
    탈, 줄수 = [], 0
    for 시작 in 머리자리:
        급 = len(줄들[시작]) - len(줄들[시작].lstrip("#"))
        끝 = len(줄들)
        for i in range(시작 + 1, len(줄들)):
            줄 = 줄들[i]
            if 줄.startswith("#") and (len(줄) - len(줄.lstrip("#"))) <= 급:
                끝 = i
                break
        안쪽 = 줄들[시작:끝]
        for 표 in 표들(안쪽):
            # **판정이 하나라도 든 표만 대조 표로 본다.** 같은 장에 다른
            # 표가 있을 수 있어서다 — 전부 대조 표로 보면 그 표들까지
            # 판정을 달라고 하게 되고, 그건 검사가 글 모양을 정하는 것이다
            if not any(판정인가(안쪽[i]) for i in 표):
                continue
            for i in 표:
                줄수 += 1
                if not 판정인가(안쪽[i]):
                    첫칸 = (안쪽[i].split("|")[1:2] or [""])[0].strip()
                    탈.append(f"{시작 + 1 + i}줄: 항목 {첫칸!r} 에 판정이 없습니다 "
                              f"— {' · '.join(판정들)} 중 하나여야 합니다")

    마지막줄수 = 줄수
    if not 줄수:
        탈.append(f"「{머리}」 아래에 판정이 적힌 표가 없습니다 — 표가 비었습니다")
    return 탈


def main() -> int:
    if not 보고.exists():
        print(f"!! {보고.relative_to(ROOT)} 가 없습니다 — 11-3 이 매번 덮어쓰라고 한 파일입니다.")
        return 1
    글 = 보고.read_text(encoding="utf-8")
    탈 = 본다(글)
    이름 = 보고.relative_to(ROOT).as_posix()
    if 탈:
        print(f"!! {이름} 의 지시문 대조 표가 {len(탈)}곳 어긋납니다.")
        for 말 in 탈:
            print(f"  {말}")
        print("   모양은 CLAUDE.md 11-3 4단계에 있습니다.")
        return 1
    print(f"{이름} 에 지시문 대조 표가 있습니다 (항목 {마지막줄수}줄). "
          "**번호가 그 지시문과 맞는지는 안 봅니다** — 사람과 검토자가 봅니다.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
