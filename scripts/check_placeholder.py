# -*- coding: utf-8 -*-
r"""검토용 보고에 **아직 안 채운 자리**가 남았는지 본다 (11-3 · 2026-09-12).

## 왜 검사인가

보고가 **없는 것을 있다고 적은 것이 네 판째**입니다. 마지막 판에서는
수용 기준 표에 O 를 찍어 두고 그 O 가 가리키는 장이 빈 자리였습니다.
매번 커밋 전 검토가 잡았고, 매번 다음 판이 같은 자리를 다시 밟았습니다.

그전 판이 「보고를 스스로 훑어라」 는 지시를 받고도 놓쳤습니다 —
훑는 범위를 스스로 좁혔기 때문입니다: **「값이 틀렸나」 는 보고
「값이 아직 없나」 는 안 봤습니다.** 사람이 매번 기억하는 것으로는 안
닫히는 자리라, 11-2 가 「사람이 조심할 때를 정하지 말고 매번 도는
검사로 둔다」 고 적어 둔 그대로 옮깁니다.

## 무엇을 보나 — 둘입니다

**하나. 채울 자리를 표시해 둔 말**이 `docs/review/최근.md` 에 남아 있는가.
찾는 말은 아래 `찾는꼴` 하나이고, 이 파일 밖에 적지 않습니다.

**둘. 수용 기준 표가 가리킨 자리가 실제로 있는가** (2026-09-12 에 더했습니다).
그 표의 「어디서 잰다」 칸이 `11장` 이라고 적었는데 **보고에 11장이 없으면**
그 줄의 O 는 아무것도 안 가리킵니다. 바로 그것이 이 검사를 만든 그 판에서
한 번 더 났고(커밋 전 검토 [B]), **첫째 규칙은 그것을 못 봤습니다** —
빈 자리가 아니라 **없는 자리**였기 때문입니다.

**목록을 두지 않습니다**(10장). 「보고에 몇 장이 있어야 한다」 를 적어 두면
판마다 그 목록을 고쳐야 하고, 안 고치면 그 줄만 조용히 안 봅니다. 대신
**보고가 스스로 가리킨 것만** 봅니다 — 가리키지 않으면 볼 것도 없습니다.

**살아 있는 보고만 봅니다. 얼린 판(`docs/review/<날짜>-….md`)은 안
봅니다.** 얼린 판은 11-3 이 「한 글자도 고치지 않는다」 고 못박은 그
판의 사실이고, 실제로 **여러 판이 그 말을 담고 있습니다** — 검토자가
「여기가 아직 빈 자리다」 라고 짚은 대목이 그대로 얼려 있기 때문입니다.
그것까지 보면 고칠 수 없는 파일 때문에 영영 빨갛고, 그러면 사람이
검사를 통째로 안 보게 됩니다(11-3 이 얼린 판을 시험에서 뺀 것과 같은
자리).

**검토자 원문 덩어리도 안 봅니다.** 같은 이유입니다 — 검토자가 빈
자리를 짚으려면 그 말을 써야 하고, 구현자가 그 자리를 다 채운 뒤에도
**짚은 문장은 원문 그대로 남습니다**(11-3 이 「원문을 그대로 싣는다」
고 정했습니다). 안 빼면 고친 판이 빨갛습니다. 실제로 지난 두 판의
원문에 그 말이 들어 있었습니다.

## 이것으로 안 닫히는 것

**그 꼴이 아닌 빈 자리는 못 봅니다** — 표의 칸이 통째로 비어 있는 것,
「나중에 적음」 처럼 사람 말로 적어 둔 것, 값이 있는데 틀린 것.
글자를 찾는 검사라 그렇습니다(10장). **안 보는 것을 본다고 적지
않습니다** — 그 자리는 여전히 사람과 검토자가 봅니다.

둘째 규칙의 경계도 적어 둡니다.

- **칸의 맨 앞만 봅니다.** `1-1(없음) · 1-2(넷)` 이면 앞엣것만 봅니다 —
  칸 안의 모든 수를 보려 들면 「22일」·「7일」 같은 멀쩡한 수가 장 번호로
  읽힙니다
- **표로 적어야 봅니다.** 수용 기준을 목록으로 적으면 안 봅니다 — 칸을
  나누는 줄이 없으면 어디가 「어디서 잰다」 인지 기계가 못 가릅니다
- **수용 기준 표 밖은 안 봅니다.** 지시문 대조 표가 「11장」 이라고 적어도
  여기서는 안 잡습니다. 그 표의 판정 칸은 문장이라 맨 앞이 판정 낱말이고,
  가리키는 자리는 문장 가운데 있습니다
- **다른 문서의 장을 가리키는 것과 못 갈립니다.** 칸이 그냥 `11장` 으로
  시작하면 이 보고의 11장으로 봅니다 — CLAUDE.md 를 가리킬 생각이면
  `CLAUDE.md 11-3` 처럼 문서 이름을 앞에 적습니다. 그게 읽는 사람에게도
  맞습니다

    .venv\Scripts\python.exe scripts/check_placeholder.py
"""

from __future__ import annotations

import pathlib
import re
import sys

if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(errors="replace")

ROOT = pathlib.Path(__file__).resolve().parent.parent
보고 = ROOT / "docs" / "review" / "최근.md"

# 찾는 말. 앞에 이름이 붙은 꼴(`COMMIT_…` · `PYTEST_…`)도 이 한 낱말을 담는다
찾는꼴 = re.compile("[A-Z0-9_]*PLACEHOLDER[A-Z0-9_]*")

# 보고가 자기 장·절을 여는 줄. `# 8. …` 과 `## 6-1. …`
장머리 = re.compile(r"^#\s+(\d+)\.")
절머리 = re.compile(r"^##\s+(\d+)-(\d+)\.")

# 수용 기준 표를 여는 머리. **여럿이면 전부 보고, 같은 급 이상의 머리에서
# 닫는다** — 장으로만 잡으면 `## 8-1. 수용 기준` 처럼 절로 둔 판을 영영 안
# 보고, 머리를 만날 때마다 닫으면 그 장 안에 소제목 하나만 있어도 그 아래
# 표를 안 본다. 둘 다 **검사가 말없이 아무것도 안 보는** 자리다.
기준머리 = "수용 기준"

# 칸이 「이 보고의 어디」 를 가리키는 꼴로 시작하는가. **맨 앞만 본다.**
#
# **두 자리까지만 받는다.** 안 그러면 `2026-09-09` 같은 날짜가 절 번호로
# 읽힌다 — 장이 2026 개인 보고는 없다.
칸앞 = re.compile(r"^\**\s*(\d{1,2})(?:장|-(\d{1,2}))(?!\d)")

# **실패할 때 사정을 함께 말한다.** 안 말하면 처음 밟는 사람이 없는 장을
# 만들러 간다 — 다른 문서를 가리킬 생각이었을 뿐인데도.
딴문서 = " (다른 문서를 가리킬 생각이면 `CLAUDE.md 11-3` 처럼 문서 이름을 앞에 적습니다)"

# 검토자 원문 덩어리의 두 끝. 11-3 이 정한 글자다.
#
# **줄이 그 글자로 시작할 때만 경계로 본다.** 「들어 있으면」 으로 두면
# **본문이 그 표시를 인용하는 순간 그 아래가 통째로 검사 밖**이 된다 —
# 이 저장소는 규약 글자를 자주 인용하고, 이 파일의 설명문 자체가 그렇다.
# 2026-09-12 커밋 전 검토가 재어 짚었다.
원문시작 = "━━━ 검토자 여기부터"
원문끝 = "━━━ 검토자 여기까지"


def 가리킨자리(줄들: list[tuple[int, str]]) -> list[str]:
    """수용 기준 표가 가리킨 장·절이 보고에 실제로 있는가.

    **보고가 스스로 가리킨 것만 본다** — 있어야 할 장의 목록을 두지 않는다
    (10장). 가리키지 않으면 볼 것이 없고, 가리켰으면 그 자리가 있어야 한다.
    """
    장들 = {int(m.group(1)) for _, 줄 in 줄들 if (m := 장머리.match(줄))}
    절들 = {(int(m.group(1)), int(m.group(2)))
            for _, 줄 in 줄들 if (m := 절머리.match(줄))}

    탈, 기준안, 급 = [], False, 0
    for 번호, 줄 in 줄들:
        if 줄.startswith("#"):
            이번급 = len(줄) - len(줄.lstrip("#"))
            if 기준머리 in 줄:
                기준안, 급 = True, 이번급
            elif 기준안 and 이번급 <= 급:
                기준안 = False
            continue
        if not 기준안 or not 줄.startswith("|"):
            continue
        for 칸 in 줄.split("|")[1:-1]:
            m = 칸앞.match(칸.strip())
            if not m:
                continue
            장 = int(m.group(1))
            if m.group(2) is not None:
                if (장, int(m.group(2))) not in 절들:
                    탈.append(f"{번호}줄: 수용 기준이 {장}-{m.group(2)} 을 가리키는데 "
                              f"보고에 그 절이 없습니다{딴문서}")
            elif 장 not in 장들:
                탈.append(f"{번호}줄: 수용 기준이 {장}장을 가리키는데 "
                          f"보고에 그 장이 없습니다{딴문서}")
    return 탈


def 본다(글: str) -> list[str]:
    """탈이 있으면 그 말들을 돌려준다 — **빈 목록이 통과다.**

    부르는 곳이 둘이다(이 파일의 `main` 과 시험) — 파일을 만들지 않고 글로
    재려고 갈라 두었다. 두 곳에서 따로 판정하면 시험이 검사와 다른 것을 본다
    (`check_handoff` 와 같은 꼴).
    """
    탈, 원문안, 밖 = [], False, []
    for 번호, 줄 in enumerate(글.splitlines(), start=1):
        if 줄.startswith(원문시작):
            원문안 = True
        elif 줄.startswith(원문끝):
            원문안 = False
            continue
        if 원문안:
            continue
        밖.append((번호, 줄))
        for m in 찾는꼴.finditer(줄):
            탈.append(f"{번호}줄: {m.group(0)}")
    return 탈 + 가리킨자리(밖)


def main() -> int:
    if not 보고.exists():
        print(f"!! {보고.relative_to(ROOT)} 가 없습니다 — 11-3 이 매번 덮어쓰라고 한 파일입니다.")
        return 1
    탈 = 본다(보고.read_text(encoding="utf-8"))
    이름 = 보고.relative_to(ROOT).as_posix()
    if 탈:
        print(f"!! {이름} 에 아직 안 채운 자리가 {len(탈)}곳 있습니다.")
        for 말 in 탈:
            print(f"  {말}")
        print("   채우거나, 그 자리가 왜 비는지 보고 본문에 적습니다 (11-3).")
        return 1
    print(f"{이름} 에 안 채운 자리 표시가 없고, 수용 기준이 가리킨 장·절이 "
          f"전부 있습니다. (얼린 판과 검토자 원문은 안 봅니다)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
