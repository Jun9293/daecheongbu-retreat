def test20_a01_못_심은_갈래를_따로_세고_말한다():
    """부서 리더에게는 아예 없는 자리가 있다 — 거기에 고장을 심을 수
    없고, 그때 ✗ 가 아니라 **「못 심음」** 으로 나오는 것이 정답이다.

    못 심은 것을 「잡았다」 로도 「놓쳤다」 로도 세면 안 된다.
    """
    글 = "\n".join(_코드())
    자리 = 글[글.index("const 자가시험"):]
    assert "못심은갈래++" in 자리
    assert "못 심음" in 글
    # 못 심은 것은 놓친 것이 아니다
    앞 = 자리[:자리.index("const 걷어낸다")]
    assert "continue;" in 앞, "못 심으면 그 갈래를 건너뛰어야 한다"


