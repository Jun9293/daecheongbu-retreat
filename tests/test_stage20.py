def test20_p01_찍는_길과_세는_길이_각각_하나다():
    """③ **본 것이 0 이면 실패다** — 둘 다 실제로 있어야 하고, 각각
    하나여야 한다. 둘이 넘으면 손으로 맞추는 자리가 다시 생긴 것이다.

    2026-09-09 에는 찍는 자리 55 · 세는 자리 55 였는데 **짝이 셋
    어긋나** 있었다(검토가 찾았다). 수가 같다고 짝이 맞는 것이 아니라,
    **길이 하나여야** 어긋날 자리가 없다.
    """
    줄들 = _코드()
    찍 = 찍는자리(줄들)
    셈 = 세는자리(줄들)
    assert len(찍) == 1, f"✗ 를 찍는 자리가 하나가 아니다: {찍}"
    assert len(셈) == 1, f"실패로 세는 자리가 하나가 아니다: {셈}"
    # 그 하나가 같은 함수 안이어야 한다 — 떨어져 있으면 여전히 두 길이다
    assert abs(찍[0] - 셈[0]) <= 3, f"찍는 줄과 세는 줄이 떨어져 있다: {찍} {셈}"


def test20_p02_그_하나가_잰다_안이다():
    """이름이 있어야 부르는 쪽이 그것을 지난다."""
    줄들 = _코드()
    글 = "\n".join(줄들)
    시작 = 글.index("const 잰다 = (ok, 라벨, 까닭)")
    자리 = 글[시작:시작 + 300]
    assert "results.push(" in 자리 and "errors.push(" in 자리
    # 까닭을 안 주면 라벨을 쓴다 — 「✗ 인데 셀 말이 없다」 가 없게
    assert "까닭 === undefined" in 자리


def test20_p03_안_세는_줄을_심으면_걸린다():
    """막는 쪽. 옛 모양(찍기만 하고 안 세기)을 심어서 이 시험이 잡는지.

    **줄을 쪼개 심은 것도 잡는다** — 검토가 그것으로 두 계수기를 다
    빠져나갔습니다. 그래서 세는 단위를 줄에서 **문장**으로 옮겼습니다.
    """
    줄들 = _코드()
    for 심을것 in (["    results.push((ok ? '✓' : '✗') + ' 심은 판정');"],
                 ["    results.push(",
                  "      (false ? '✓' : '✗') + ' 줄을 쪼개 심은 판정');"]):
        심음 = 줄들 + 심을것
        assert len(찍는자리(심음)) == 2, f"심었는데 안 세어진다: {심을것}"
        # 세는 자리는 그대로다 — 이것이 옛날에 조용하던 그 모양
        assert len(세는자리(심음)) == 1
    # 세는 쪽을 몰래 부르는 것도 잡는다
    assert len(세는자리(줄들 + ["    errors.push('몰래');"])) == 2


def test20_p04_부르는_쪽이_실제로_있다():
    """③ 잰다 를 만들어 두고 아무도 안 부르면 화면에 판정이 안 나온다."""
    글 = "\n".join(_코드())
    부름 = len(re.findall(r"(?<!const )잰다\(", 글))
    assert 부름 >= 40, f"잰다 를 부르는 자리가 너무 적다: {부름}"


