"""찍는 자리와 세는 자리 맞추기 (+ 자가시험 두 계정).

점검이 ✗ 를 찍는 것과 `errors` 에 세는 것을 **따로** 하고 있었다. 둘을
손으로 맞춰야 했고 실제로 셋이 어긋나 있었다 — ✗ 를 찍고도 안 세어서
그 줄이 빨개져도 `통과: true` 였다. 갈래 단위인 자가시험은 그 틈을
못 본다(봐둘것 AI-d).

그래서 심는 대신 **코드에서 견준다** — ✗ 를 찍는 길과 `errors` 에
넣는 길이 각각 하나뿐인지.

**이 파일은 낱말을 잰다.** 점검 스크립트는 브라우저에서만 돌기 때문에,
여기서는 그것이 **어떤 모양으로 적혀 있는지**를 본다 — 실제로 돌린
결과는 `docs/review/최근.md` 에 있다.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
점검 = ROOT / "docs" / "checks" / "drawer.js"


def _코드(글: str | None = None) -> list[str]:
    """주석을 걷어낸 점검 스크립트 — **줄 수를 지킨다.**

    글자를 찾는 시험은 코드와 설명을 못 가린다(10장). 그런데 여기서는
    「몇 줄이 그러한가」 를 세므로, 지우는 대신 **빈 줄로 바꾼다.**
    """
    글 = 점검.read_text(encoding="utf-8") if 글 is None else 글
    나온것, 블록 = [], False
    for 줄 in 글.splitlines():
        if 블록:
            나온것.append("" if "*/" not in 줄 else 줄.split("*/", 1)[1])
            블록 = "*/" not in 줄
            continue
        if "/*" in 줄:
            머리 = 줄.split("/*", 1)[0]
            if "*/" in 줄:
                나온것.append(머리 + 줄.split("*/", 1)[1])
            else:
                나온것.append(머리)
                블록 = True
            continue
        나온것.append(re.sub(r"(?<!:)//.*$", "", 줄))
    return 나온것


def _문장(줄들: list[str], i: int, at: int) -> str:
    """`push(` 다음부터 짝이 맞는 닫는 괄호까지 — **줄이 아니라 문장으로.**

    줄로 세면 `results.push(` 와 `✗` 를 **다른 줄에** 적는 것으로 두
    계수기를 다 빠져나갑니다(검토가 심어서 보였습니다). 이 판의 주장이
    「길이 하나라 어긋날 자리가 없다」 이므로 그 문을 닫습니다.
    """
    글, 깊이 = [], 1
    for j in range(i, min(i + 12, len(줄들))):
        줄 = 줄들[j]
        for k in range(at if j == i else 0, len(줄)):
            글.append(줄[k])
            if 줄[k] == "(":
                깊이 += 1
            elif 줄[k] == ")":
                깊이 -= 1
                if 깊이 == 0:
                    return "".join(글)
    return "".join(글)


def _문장들(줄들: list[str], 이름: str) -> list[tuple[int, str]]:
    """`이름(` 이 여는 문장 전부 — (줄 번호, 문장)."""
    나온것 = []
    for i, 줄 in enumerate(줄들):
        at = 0
        while True:
            k = 줄.find(이름, at)
            if k == -1:
                break
            나온것.append((i + 1, _문장(줄들, i, k + len(이름))))
            at = k + len(이름)
    return 나온것


def 찍는자리(줄들: list[str]) -> list[int]:
    """✗ 를 화면에 찍는 자리 (1부터) — **문장 단위**."""
    return [n for n, 문장 in _문장들(줄들, "results.push(") if "✗" in 문장]


def 세는자리(줄들: list[str]) -> list[int]:
    """실패로 세는 자리 (1부터)."""
    return [n for n, _ in _문장들(줄들, "errors.push(")]


