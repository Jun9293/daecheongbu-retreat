def test20_c01_사본_주소_우회가_머리말과_기준_문서에_있다():
    """정적 주소가 1년 immutable 이라 사본을 고쳐도 옛 것이 온다.
    실제로 그것으로 여섯 판을 헛돌렸다 — 「길이를 찍어 보라」 까지
    적어 두지 않으면 다음 사람도 모르고 지나간다."""
    머리 = 점검.read_text(encoding="utf-8")
    머리 = 머리[: 머리.index("const 점검 = async")]
    문서 = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    자리 = 문서[문서.index("### 2. 재시작하고"):문서.index("### 3. CLAUDE.md")]
    for 글, 이름 in ((머리, "점검 머리말"), (자리, "CLAUDE.md 11-3 2단계")):
        assert "immutable" in 글, f"{이름} 에 캐시 이야기가 없다"
        assert "cache" in 글 and "reload" in 글, f"{이름} 에 우회가 없다"
        assert "길이" in 글, f"{이름} 에 확인하는 법이 없다"


