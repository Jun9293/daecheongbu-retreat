"""자가시험 뒤처리 판 — 사람이 2026-09-24 에 정한 셋 (CLAUDE.md 10장 · 4-9).

| 정한 것 | 어디서 재나 |
|---|---|
| ① 표에 「못 잰 수」·「실패 수」를 되살린다 | 아래 `가` |
| ② 자국 둘 — 확인 요청은 개발 서버에서만 · 드로어 폭은 되돌린다 | 아래 `나` |
| ③ 자가시험이 왜 오래 걸리나 | 브라우저에서 재는 것이라 여기서는 못 잰다 |

**막는 쪽과 막히면 안 되는 쪽을 함께 잰다** (11-3). ② 의 「막는 쪽」 은
브라우저에서 **운영 주소로 꾸며 실제로 재었고**(보고 5장), 여기 있는 것은
그 구조가 다시 무너지지 않게 붙드는 자리다 — 판단이 두 곳으로 갈리거나,
되돌리기가 `finally` 밖으로 나가거나, 값이 없던 경우를 잃는 것.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
점검JS = (ROOT / "docs" / "checks" / "drawer.js").read_text(encoding="utf-8")


# ── 가. ① 표의 두 칸 ─────────────────────────────────────────────────

def test67_a01_표에_못_잰_수와_실패_수가_있다():
    """**그 두 수가 BI-h 를 가르는 수다** — 못쟀음 한 줄이 곧 상한을 다 쓴
    기다림 한 번이라, 그 칸이 없으면 「왜 오래 걸리나」 를 표만 보고는
    못 가른다. 앞 판이 걷었던 까닭은 지시문이 좁게 적혀서였다.

    **못 심은 갈래에도 칸이 있어야 한다** — 없으면 그 줄만 칸 수가 달라
    표가 어긋나고, 「0 이라서 없는 것」 과 「잴 자리가 아니라 없는 것」 이
    같은 빈칸이 된다."""
    자리들 = re.findall(r"표\.push\(\{[^;]+?\}\);", 점검JS, re.S)
    # **센 것이 0 이면 성공이 아니라 실패다** (11-3). 이 정규식은 객체 안에
    # `;` 가 하나만 들어가도 그 줄을 놓치는데, 그러면 칸을 지워도 초록이다
    assert len(자리들) == 2, f"표를 내는 자리가 둘이어야 한다 — {len(자리들)}개 찾음"
    for 자리 in 자리들:
        assert "못잰수:" in 자리, 자리
        assert "실패수:" in 자리, 자리


def test67_a02_진행_표시도_두_수를_싣는다():
    """진행 표시는 **안 끝나도 읽는 자리**다(그것이 이 표시를 둔 까닭이다).
    표에만 두면 판이 한복판에서 멈췄을 때 그 수를 못 본다."""
    at = 점검JS.index("window.__진행.지난갈래.push(g.갈래 + (잡혔나")
    줄 = 점검JS[at:점검JS.index(";", at)]
    assert "못잼" in 줄 and "실패" in 줄, 줄


# ── 나. ② 자국 둘 ────────────────────────────────────────────────────

def test67_b01_개발_서버_판단은_한_곳이고_모르면_안_보낸다():
    """**「개발이면 보낸다」 가 아니라 「개발이라고 확인된 때만 보낸다」** 다.
    주소를 못 읽는 자리가 생겨도 조용히 보내는 쪽으로 기울면 안 된다 —
    그 자리는 남의 알림함에 요청을 세운다.

    판단이 두 곳이 되면 한쪽만 고쳐진다(이 저장소가 가장 자주 고쳐 온 모양)."""
    assert 점검JS.count("const 개발서버인가") == 1
    at = 점검JS.index("const 개발서버인가")
    식 = 점검JS[at:점검JS.index("})();", at)]
    assert "catch" in 식 and "return false" in 식, 식
    assert 점검JS.count("hostname") == 1, "주소를 보는 자리가 늘었다"


def test67_b02_확인_요청은_그_판단에만_걸린다():
    """막는 쪽과 도는 쪽이 **같은 `if`** 에서 갈려야 한다 — 따로 적으면
    한쪽 조건만 바뀌어 둘 다 돌거나 둘 다 안 도는 날이 온다."""
    at = 점검JS.index("if (canEdit && firstDept && !개발서버인가)")
    토막 = 점검JS[at:at + 600]
    assert "건너뜀 (운영에서는 안 보냄" in 토막
    assert "} else if (canEdit && firstDept) {" in 토막, 토막


def test67_b03_드로어_폭은_finally_에서_되돌린다():
    """**점검이 중간에 죽어도 사람의 폭은 되돌아가야 한다.** 그래서
    `finally` 다 — `try` 끝에 두면 ✗ 하나에 그대로 남는다.

    그리고 **값이 없던 것도 값이다** — 없었으면 지워야지, 기본값을 새로
    써 넣으면 그것도 자국이다."""
    at = 점검JS.index("const 폭되돌리기")
    되돌 = 점검JS[at:점검JS.index("};", at)]
    assert "removeItem" in 되돌, "값이 없던 경우를 안 다룬다"

    끝 = 점검JS.index("  } finally {")
    토막 = 점검JS[끝:끝 + 400]
    assert "폭되돌리기()" in 토막, 토막
    # **실패를 삼키지 않는다** — 조용히 넘어가면 다음 판이 또 남의 값 위에서 잰다
    assert "잰다(false" in 토막, 토막


def test67_b04_기억하는_자리가_try_보다_앞이다():
    """`try` 안에서 기억하면 **그 줄 앞에서 죽었을 때** 되돌릴 값이 없다 —
    그러면 `finally` 를 둔 뜻이 없어진다."""
    줄 = 점검JS.splitlines()
    기억 = next(i for i, x in enumerate(줄) if "폭처음 = null" in x)
    바깥try = next(i for i, x in enumerate(줄) if x.rstrip() == "  try {")
    assert 기억 < 바깥try, (기억, 바깥try)


def test67_a03_기준_문서가_그_칸_이름을_말한다():
    """**스크립트와 CLAUDE.md 가 같은 이름을 말해야 한다.** 기준 문서가
    앞의 두 칸만 세고 있으면, 다음 사람이 뒤의 둘을 규칙 위반으로 보고
    지운다 — 「만」 이라고 적어 두면 그렇게 된다고 앞 판이 이미 겪었다.

    **그리고 왜 있는지가 함께 적혀 있어야 한다.** 까닭 없는 칸은 다음에
    또 걷힌다 — 실제로 한 번 걷혔고, 그 자리가 이 판의 지시문 1 이다."""
    md = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    at = md.index("갈래별 표에 「안 심음」 칸을 두지 않습니다")
    장 = md[at:at + 1400]
    assert "못잰수" in 장, "되살린 칸 이름이 기준 문서에 없다"
    assert "실패수" in 장, "되살린 칸 이름이 기준 문서에 없다"
    assert "BI-h" in 장, "그 칸이 왜 있는지가 안 적혀 있다"


