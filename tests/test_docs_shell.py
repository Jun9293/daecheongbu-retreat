def test_껍데기_04b_검사_이름을_적은_확인_출력은_안_걸린다():
    """**이 검사가 실제로 이 자리에서 빨갰다.**

    11-3 이 보고에 확인 결과를 붙이라고 정했는데, 그 결과의 이름이
    검사하는 글자 그대로다 — 「cd /d 를 되돌리면 … 1 failed」.
    10장이 산문에서 막은 것(test_껍데기_02)이 **보고의 기계 출력으로**
    옮겨간 모양이다. 트레이스백(04)·URL 인코딩(05)과 같은 자리.

    가르는 것은 **뒤에 경로가 오는가** — 명령이면 온다.
    """
    보고 = chr(10).join([
        "```",
        "cd /d 를 되돌리면                       1 failed",
        "cd /d 는 왜 안 되나                     확인함",
        "```"])
    assert 걸린줄(보고) == [], 걸린줄(보고)

    진짜명령 = chr(10).join(["```", 'cd /d "C:\\x"', "```"])
    assert [x[1] for x in 걸린줄(진짜명령)] == ["cd /d"], 걸린줄(진짜명령)


