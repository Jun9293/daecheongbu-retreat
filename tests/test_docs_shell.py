    assert 걸린줄(측정표) == [], 걸린줄(측정표)

    진짜 = chr(10).join(["```", "sc query Cloudflared", "curl http://x/", "```"])
    assert [x[1] for x in 걸린줄(진짜)] == ["별칭", "별칭"], 걸린줄(진짜)


