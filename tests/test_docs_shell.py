# -*- coding: utf-8 -*-
"""문서의 명령은 PowerShell 로 적는다 (11-2).

문서의 명령이 두 껍데기로 섞여 있었다. **cmd 문법을 PowerShell 창에
붙여 넣으면 "붙여넣었는데 명령이 안 돈다" 가 된다.** 오류가 눈에 띄게
나기도 하고, `cd /d` 처럼 **파싱은 되고 실행만 실패하는** 것도 있다.

재 본 것 (Windows PowerShell 5.1):

    잇기 한 줄만 넣으면   -> 인자로 딸려 들어간다: ['data/x.json', '~']  exit 0
    두 줄을 한꺼번에      -> 파스 단계에서 실패 (첫 줄도 안 돈다)
    cd /d "..."           -> 파싱은 통과하고 실행이 실패한다
    sc                    -> Set-Content 별칭이라 파일이 만들어진다
    curl                  -> Invoke-WebRequest 별칭이라 HTML 이 안 나온다
    curl.exe · sc.exe     -> 원래 것이 그대로 돈다

(위의 `~` 는 이 파일이 스스로 검사에 걸리지 않게 바꿔 적은 것이다.
실제로는 cmd 의 줄 잇기 글자다.)

**대화형 콘솔에 두 줄을 한 번에 붙여넣는 경우는 재지 않았다** — 호스트와
PSReadLine 판에 따라 갈린다. 그래서 "첫 줄이 이미 실행된 뒤에 오류를 본다"
고 적지 않는다. **잰 것만 적는다.**

**소스를 읽는 시험이지만 이 자리는 그것이 맞다** — 재는 대상이 문서의
글자 자체이지 코드의 동작이 아니다.

`.bat` 는 보지 않는다. 그건 cmd 가 읽는다 (11-2 의 유일한 예외).

**정본은 CLAUDE.md 11-2 다.** 위 측정표는 거기서 옮겨 온 것이고,
한쪽만 고치면 기준 문서와 시험이 서로 반대를 말하게 된다 — 실제로
한 번 그랬다.
"""

from __future__ import annotations

import ast
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent

# cmd 문법. **글자를 여기 한 번만 적는다** — 이 파일이 스스로 검사에
# 걸리지 않도록 인용은 전부 이 이름을 쓴다 (10장).
잇기 = chr(94)

울타리 = re.compile(r"^\s*(```|~~~)")

# `set X=값` (cmd) — `Set-Content` 나 문장 속의 "set" 은 걸리지 않게
# 줄 첫머리 + 등호까지 본다.
옛변수쓰기 = re.compile(r"^\s*set\s+[A-Za-z_][A-Za-z0-9_]*\s*=")
# `%VAR%` (cmd). 이 저장소의 문서에는 헷갈리는 것이 둘 더 있어서 갈라야 한다.
#
#   URL 인코딩   %EC%B5%9C  — 11-3 이 보고에 raw 주소를 붙이라고 정했다
#   퍼센트 서식  %Y%m%d     — backup.py 의 날짜 서식이 문서에 인용된다
#
# 가르는 조건 둘 — 이름이 **두 글자 이상**이고(서식은 한 글자), **hex 두
# 자리 뒤에 바로 `%` 가 오는 꼴이 아니다**(그건 URL 인코딩이다).
# 그래서 `%AB%` 처럼 두 글자 hex 로 된 변수는 놓친다 — 이 저장소에 없고,
# 놓치는 쪽이 보고를 못 적게 만드는 것보다 낫다.
옛변수읽기 = re.compile(r"%(?![0-9A-Fa-f]{2}%)[A-Za-z_][A-Za-z0-9_]+%")
# `cd /d` (cmd) — PowerShell 의 `cd` 는 `Set-Location` 별칭이라 이 스위치를
# 받지 못한다. **이 판을 막은 것이 정확히 이것이다** — 배포 안내 1장의
# 첫 명령이었고, 문법이 아니라 스위치라 줄 잇기 검사에는 안 걸렸다.
#
# **뒤에 경로가 와야 명령이다.** 그냥 `^\s*cd\s+/[dD]\b` 로 두었더니
# 검토용 보고(11-3)에 붙인 확인 결과 — 「cd /d 를 되돌리면  1 failed」 —
# 가 걸렸다. 10장의 「금지하는 도구가 그것을 설명하려고 스스로 담는다」
# 가 산문에서는 막혔는데(test_껍데기_02) **보고의 기계 출력으로 옮겨간
# 것**이다. 트레이스백을 가른 것과 같은 자리다.
옛경로이동 = re.compile(r"""^\s*cd\s+/[dD]\s+["'A-Za-z0-9.\\%$]""")

# **PowerShell 이 같은 이름의 별칭으로 가리는 명령.** 이름만 치면 원래
# 프로그램이 아니라 별칭이 돌고, 오류도 안 난 채 엉뚱한 일이 생긴다 —
# `sc query …` 는 화면에 아무것도 안 내고 `query` 라는 파일을 만든다.
# **이 판에서 실제로 깨져 있던 둘(sc · curl)이 전부 이 종류였고, 위의
# 규칙 셋 어디에도 안 걸렸다.**
#
# **이 목록이 전부가 아니다.** 새 명령을 문서에 적을 때는
# `Get-Command <이름> -All` 로 한 번 봐야 한다 — 같은 이름이 둘 나오면
# `.exe` 를 붙인다. 여기 없다고 안전하다는 뜻이 아니다.
#
# 실제로 재서 갈랐다 — 걸리는 것: sc · curl · where.
# 안 걸리는 것: copy(Copy-Item 이 위치 인자를 그대로 받는다) · mkdir(함수) ·
# net · setx · py.
#
가려진명령 = re.compile(r"^\s*(sc|curl|where)\s+\S")

# **설명 줄은 명령이 아니다.** 이 저장소의 측정표는 `이름 -> 무슨 일이
# 생기나` 꼴이고, CLAUDE.md 11-2 와 이 파일 머리말이 그 표를 담는다.
# 그걸 안 가르면 **금지하는 것을 설명하는 글이 스스로 걸린다** (10장).
# 이번 판에서 실제로 네 번 걸렸다 — 트레이스백 · URL 인코딩 ·
# 「cd /d 를 되돌리면 … 1 failed」 · 그리고 이 측정표.
설명줄 = re.compile(r"\s->\s")


def 블록줄(글: str):
    """펜스 안 + 4칸 이상 들여쓴 줄을 (줄번호, 내용) 으로.

    **들여쓴 것도 본다** — `docs/검토-원칙.md` 가 "코드블록 안에 또
    코드블록을 열지 않는다, 인용은 들여쓰기로" 로 정해 두어서
    `docs/봐둘것.md` 는 펜스를 아예 안 쓴다. 펜스만 보면 그 파일이
    통째로 검사 밖이다.

    블록인용(`>`) 안의 펜스도 센다.
    """
    안 = False
    for i, 줄 in enumerate(글.split(chr(10)), 1):
        벗 = 줄.lstrip("> " + chr(9))
        if 울타리.match(줄) or 울타리.match(벗):
            안 = not 안
            continue
        if 안:
            yield i, 줄
            continue
        본 = 줄.lstrip(">")
        if 본.strip() and (len(본) - len(본.lstrip())) >= 4:
            yield i, 줄


def _잇기인가(줄: str) -> bool:
    """줄 끝의 그 글자가 **명령의 줄 잇기**인가.

    파이썬 트레이스백의 자리 표시와 갈라야 한다 — 11-3 이 보고
    (`docs/review/최근.md`)에 기계 출력을 붙이라고 정해 두었고,
    파이썬 3.11+ 의 오류 표시는 줄 끝이 이 글자다.

    가르는 조건 둘 — **하나뿐이고**, **앞에 명령이 있다.**
    """
    끝 = 줄.rstrip()
    if not 끝.endswith(잇기):
        return False
    if 끝.count(잇기) != 1:
        return False               # 여럿이면 자리 표시다
    앞 = 끝[:-1]
    return bool(앞.strip())        # 앞이 공백뿐이면 자리 표시다


def 걸린줄(글: str):
    """(줄번호, 무엇이, 내용). 무엇이 = 잇기 / set / %VAR% / cd /d / 별칭"""
    난것 = []
    for i, 줄 in 블록줄(글):
        if 설명줄.search(줄):
            continue
        if _잇기인가(줄):
            난것.append((i, "줄 잇기", 줄.rstrip()))
        elif 옛변수쓰기.match(줄.lstrip(">")):
            난것.append((i, "set X=", 줄.rstrip()))
        elif 옛변수읽기.search(줄):
            난것.append((i, "%VAR%", 줄.rstrip()))
        elif 옛경로이동.match(줄.lstrip(">")):
            난것.append((i, "cd /d", 줄.rstrip()))
        elif 가려진명령.match(줄.lstrip(">")):
            난것.append((i, "별칭", 줄.rstrip()))
    return 난것


def 볼파일():
    """문서 + **스크립트의 모듈 독스트링** (11-2 — 규칙 안이다).

    `docs` 아래의 `.txt`(이름-확인됨 · 이름-남은곳)와 `.claude/` 의
    안내문도 본다. 지금 그 셋에 명령은 없지만, **자리를 넓히는 것이
    목록을 짜는 것보다 낫다** — 어디를 안 보는지 사람이 기억하고
    있어야 하는 규칙은 그 기억이 틀리는 날 조용히 뚫린다.
    """
    문서 = [ROOT / "CLAUDE.md", ROOT / "README.md"]
    문서 += sorted((ROOT / "docs").rglob("*.md"))
    문서 += sorted((ROOT / "docs").rglob("*.txt"))
    문서 += sorted((ROOT / ".claude").rglob("*.md"))
    낼것 = [(p, p.read_text(encoding="utf-8")) for p in 문서 if p.exists()]
    for p in sorted((ROOT / "scripts").glob("*.py")):
        try:
            독 = ast.get_docstring(ast.parse(p.read_text(encoding="utf-8")))
        except SyntaxError:
            continue
        if 독:
            # 독스트링은 통째로 명령 블록이라 들여쓰기를 따지지 않는다
            낼것.append((p, chr(10).join("    " + x for x in 독.split(chr(10)))))
    return 낼것


def test_껍데기_01_검사가_실제로_잡는다():
    """**아무것도 안 보는 검사는 통과가 아니다** (11-3).

    아래 본 검사는 문서가 깨끗하면 늘 초록이라, 검사가 망가져도 초록이다.
    """
    나쁨 = chr(10).join(["```", "python a.py " + 잇기, "    --b c", "```"])
    assert 걸린줄(나쁨) == [(2, "줄 잇기", "python a.py " + 잇기)], 걸린줄(나쁨)

    셋 = chr(10).join(["```", "set DCB_X=1", "echo %DCB_X%",
                     'cd /d "C:\\x"', "```"])
    무엇 = [x[1] for x in 걸린줄(셋)]
    assert 무엇 == ["set X=", "%VAR%", "cd /d"], 걸린줄(셋)


