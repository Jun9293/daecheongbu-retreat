def test_껍데기_07_문서와_독스트링에_cmd_문법이_없다():
    """**여기가 본 검사다.** 문서 + `scripts/*.py` 모듈 독스트링."""
    낼것 = 볼파일()

    # **따로 센다.** 전에는 `>= 12` 하나였는데 그 문턱은 .md 만으로 이미
    # 채워져서, 독스트링 수집이 11개에서 1개로 무너져도 초록이었다.
    글 = sum(1 for p, _ in 낼것 if p.suffix in (".md", ".txt"))
    코드 = sum(1 for p, _ in 낼것 if p.suffix == ".py")
    assert 글 >= 12, f"문서를 너무 적게 본다: {글}개"
    assert 코드 >= 8, f"독스트링을 너무 적게 본다: {코드}개"

    # **센 것이 0이면 성공이 아니라 실패다** (11-3). 울타리 정규식이
    # 망가져 한 줄도 안 뽑아도 아래 단언은 전부 초록이다 — 실명 검사가
    # 29개 중 0개를 보며 초록이던 것과 같은 모양이다.
    # **정확한 수를 박지 않는다** — 문서가 자라면 시험이 막는다.
    뽑은줄 = sum(len(list(블록줄(x))) for _, x in 낼것)
    assert 뽑은줄 >= 300, f"블록을 너무 적게 뽑았다: {뽑은줄}줄"

    걸린것 = {}
    for p, 글 in 낼것:
        줄들 = 걸린줄(글)
        if 줄들:
            걸린것[str(p.relative_to(ROOT))] = 줄들
    assert not 걸린것, (
        "문서의 명령에 cmd 문법이 있다 — PowerShell 창에 붙여 넣으면 "
        f"안 돕니다 (11-2): {걸린것}")
