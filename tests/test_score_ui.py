def test_z_15b_다_채웠다가_비우면_셈한_표를_걷어낸다(판):
    """**적기만 하고 되돌리지 않으면 파일만 틀린다.**

    화면은 매번 다시 세어 맞는데 성적표로 옮겨 적히는 것은 파일 쪽이다.
    「다 채웠을 때만 적는다」 가 그 '언제' 가 아닌 때에 뚫리는 자리다.
    """
    M, 길 = 판
    for 자리 in (0, 1, 3):
        M.채운다(길, 자리, {"판정": "O"})
    assert "| 합계 | 14/21 (67%) | 3/3 (100%) |" in 길.read_text(encoding="utf-8")

    M.채운다(길, 1, {"판정": ""})              # 오누름을 취소했다
    글 = 길.read_text(encoding="utf-8")
    assert "3/3 (100%)" not in 글
    assert "| 합계 | 14/21 (67%) | / 3 |" in 글        # 생성기가 낸 빈 모양
    assert "| `다른업무` | |" in 글

    # 전부 지우면 **글자 하나까지** 원본으로 돌아간다
    for 자리 in (0, 3):
        M.채운다(길, 자리, {"판정": ""})
    assert 길.read_text(encoding="utf-8") == 표본


def test_z_15c_백분율을_만드는_곳이_하나다(판):
    """`Math.round` 와 파이썬 `round` 가 갈려 화면 13% · 파일 12% 가 됐다."""
    M, 길 = 판
    # 파이썬 `round` 는 짝수 쪽으로 — 12.5 는 12 다. 화면이 따로 세면 13 이다
    assert M.비율글(1, 8) == "1/8 (12%)"
    assert M.비율글(5, 8) == "5/8 (62%)"
    # 화면은 서버가 만든 글자를 받아 그린다 — 스스로 백분율을 세지 않는다.
    # **주석을 걷어내고 본다** — 무엇을 금지하는지 설명하려면 그 말을 적어야
    # 해서, 그대로 찾으면 고쳐 놓고도 빨갛다 (10장 · 지금까지 네 번 당했다)
    코드만 = "\n".join(줄.split("//")[0] for 줄 in M.화면.splitlines())
    assert "Math.round" not in 코드만
    assert "Math.round" in M.화면          # 설명은 남아 있다 — 검사가 그것을
    #                                       가려내고 있다는 뜻이다
    셈 = M.상태전부(길, 회의록)["셈"]
    assert 셈["비율"]["논의"] == "0/1 (0%)" and 셈["합계비율"] == "0/3 (0%)"
    assert 셈["일판비율"]["논의"] == "8/13 (62%)"
    assert 셈["일판합계비율"] == "14/21 (67%)"


