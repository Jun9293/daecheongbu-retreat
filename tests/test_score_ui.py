# ── 「놓친 것」 화면이 이미 낸 것을 보여 준다 (3판 준비) ─────────────────
#
# **2판에서 사람이 이미 낸 것을 또 적었습니다.** 「놓친 것」 을 물을 때
# 회의록만 보여 주고 그 회의의 제안 목록은 안 보여 줬기 때문입니다 —
# 사람 잘못이 아니라 화면 잘못입니다. 셋이 한 벌입니다 (11-3):
# ① 목록이 보이나 ② 겹침을 말하나 ③ **0개인 회의에서 아무것도 안 보면서
# 통과하지 않나.**

def test_z_19_놓친것_화면에_그_회의의_제안_목록이_있다(판):
    """① 보이나 — **개수가 아니라 내용까지** 본다. 개수만 세면 빈 칸
    셋을 넘겨도 통과한다."""
    M, 길 = 판
    걸음 = M.상태전부(길, 회의록)["걸음"]
    다섯 = 걸음[2]                                  # 26.05.24 의 「놓친 것」
    assert 다섯["갈래"] == "놓친것" and 다섯["짧은제목"] == "26.05.24"
    assert [x["자리"] for x in 다섯["제안들"]] == [1, 2]
    assert 다섯["제안들"][0]["종류"] == "결정사항"
    assert "광고를 6월 7일에" in 다섯["제안들"][0]["무엇"]
    assert 다섯["제안들"][1]["무엇"].startswith("「큐시트 제작」")
    # 판정도 함께 — 무엇을 O 로 봤는지 보고 적어야 겹침이 준다
    M.채운다(길, 0, {"판정": "O"})
    다시 = M.상태전부(길, 회의록)["걸음"][2]
    assert 다시["제안들"][0]["판정"] == "O"
    # 화면이 실제로 그린다. **주석을 걷어내고 본다** — 무엇을 그리는지
    # 설명하는 주석에 같은 말이 들어 있어서, 그냥 찾으면 **그리는 코드를
    # 통째로 지워도 통과한다** (10장 · `test_z_15c` 와 같은 자리)
    코드만 = "\n".join(줄.split("//")[0] for 줄 in M.화면.splitlines())
    assert "이 회의에서 낸 것" in 코드만
    assert "g.제안들.forEach" in 코드만


def test_z_20_이미_낸_것과_닮으면_말한다_막지는_않는다(판):
    """② 말하나 — **막지 않는다.** 「그 제안으로는 부족하다」 는 판단일 수
    있어서 겹쳐 적는 것이 틀린 것이 아니다. 다만 **그렇게 판단한 것인지
    모르고 적은 것인지**가 갈려야 한다."""
    M, 길 = 판
    M.채운다(길, 2, {"값": "O", "무엇": "1. 큐시트 제작 업무가 필요, 2. 회비 안내"})
    걸음 = M.상태전부(길, 회의록)["걸음"][2]
    # **막지 않았다** — 적은 것이 그대로 남는다
    assert 걸음["값"] == "O"
    assert "큐시트 제작 업무가 필요" in 걸음["무엇"]
    # **말은 한다**
    닮음 = {x["자리"] for x in 걸음["닮은것"]}
    assert 2 in 닮음, 걸음["닮은것"]          # #2 「큐시트 제작」 과 닮았다
    말 = [x for x in 걸음["닮은것"] if x["자리"] == 2][0]
    assert 말["토막"] == "큐시트 제작 업무가 필요"
    assert "큐시트" in 말["겹친낱말"]
    # 안 닮은 토막은 말하지 않는다 — 아무 말이나 하면 사람이 안 읽는다
    assert not [x for x in 걸음["닮은것"] if x["토막"] == "회비 안내"]


def test_z_21_제안이_0개인_회의에서_아무것도_안_보면_안_된다(판):
    """③ **검사가 볼 것을 실제로 보고 있는가.**

    제안이 0개인 회의는 목록도 비고 닮은 것도 없다 — 그 상태로 「통과」
    하면, 목록을 아예 안 넘겨도 시험이 초록이다. 그래서 **0개일 때는
    0개라고 말하는지**를 따로 본다.
    """
    M, 길 = 판
    걸음 = M.상태전부(길, 회의록)["걸음"]
    빈회의 = 걸음[5]
    assert 빈회의["갈래"] == "놓친것" and 빈회의["짧은제목"] == "26.09.01"
    assert 빈회의["제안들"] == [] and 빈회의["닮은것"] == []
    # **0개인 것과 목록을 안 넘긴 것이 같은 모양이면 안 된다** —
    # 화면이 그 자리에 「낸 것이 없습니다」 를 낸다
    assert "낸 것이 없습니다" in M.화면
    assert "if(!g.제안들.length)" in M.화면.replace(" ", "")
    # 그리고 **닮음 판정 자체가 도는지**를 여기서 못 본다는 것을 못 박는다 —
    # 위 test_z_20 이 그 자리다. 여기서는 0개가 0개로 나오는 것만 본다
    M.채운다(길, 5, {"값": "O", "무엇": "아무거나 적어도 닮을 것이 없다"})
    assert M.상태전부(길, 회의록)["걸음"][5]["닮은것"] == []


