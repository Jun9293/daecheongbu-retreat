def test_z_18_채우면_suggest_sample_이_못_덮는다(판):
    """가드는 **「사람이 채운 것을 기계가 덮지 않는다」** 이고 이 화면은
    **「사람이 채운다」** 다. 우회하는 것이 아니라 애초에 대상이 아니다 —
    오히려 한 칸이라도 채우면 그때부터 `--replace` 로도 못 덮어야 맞다."""
    M, 길 = 판
    스펙 = importlib.util.spec_from_file_location(
        "_ss_guard", ROOT / "scripts" / "suggest_sample.py")
    SS = importlib.util.module_from_spec(스펙)
    스펙.loader.exec_module(SS)
    assert SS.채운곳(길.read_text(encoding="utf-8")) == []
    M.채운다(길, 0, {"판정": "O"})
    assert SS.채운곳(길.read_text(encoding="utf-8"))
    with pytest.raises(SystemExit):
        SS.막는다(길, replace=True)
