def test_z_15b_다_채웠다가_비우면_셈한_표를_걷어낸다(판):
    """**적기만 하고 되돌리지 않으면 파일만 틀린다.**

    화면은 매번 다시 세어 맞는데 성적표로 옮겨 적히는 것은 파일 쪽이다.
    「다 채웠을 때만 적는다」 가 그 '언제' 가 아닌 때에 뚫리는 자리다.
    """
    M, 길 = 판
    for 자리 in (0, 1, 3):
        M.채운다(길, 자리, {"판정": "O"})
    assert "| 합계 | 14/21 (67%) | 3/3 (100%) |" in 길.read_text(encoding="utf-8")

    M.채운다(길, 1, {"판정": ""})              # 오누름을 취소했다
    글 = 길.read_text(encoding="utf-8")
    assert "3/3 (100%)" not in 글
    assert "| 합계 | 14/21 (67%) | / 3 |" in 글        # 생성기가 낸 빈 모양
    assert "| `다른업무` | |" in 글

    # 전부 지우면 **글자 하나까지** 원본으로 돌아간다
    for 자리 in (0, 3):
        M.채운다(길, 자리, {"판정": ""})
    assert 길.read_text(encoding="utf-8") == 표본


