def test38_a03_얼린_판은_안_본다(빈자리):
    """나) 얼린 판은 11-3 이 「한 글자도 고치지 않는다」 고 못박은 파일이고,
    **실제로 여러 판이 그 말을 담고 있다** — 검토자가 짚은 대목이 그대로
    얼렸기 때문이다. 그것까지 보면 고칠 수 없는 글 때문에 영영 빨갛다.

    본다 — ① 검사가 여는 파일이 **살아 있는 보고 하나**인가 ② **저장소에
    실제로 그 말을 담은 얼린 판이 있는가** — 없으면 이 줄은 아무것도 안
    보는 시험이다. 둘이 함께 서면 「얼린 판을 안 본다」 가 참이다.

    **③ 이 있었다 — 「그런데도 지금 저장소가 초록인가」.** 걷었다.
    그것은 이 검사를 pytest 에서 한 번 더 돌리는 것일 뿐이고(글검사가 이미
    돌리며 `test38_a04` 가 들어 있음을 지킨다), 값 대신 치르는 것이 있었다:
    **보고를 쓰는 동안 전체 시험이 빨개서** 그 빨강이 코드 회귀와 겉이
    같아졌고, 11-3 이 허락한 「막혀서 멈춤」 판은 보고가 덜 쓰인 채로
    끝나므로 **정의상 초록을 못 냈다.** 2026-09-12 커밋 전 검토가 짚었다.

    얼린 글을 검토자 원문으로 감싸 재 보려 했지만 **그 글 자신이 원문
    표시를 담고 있어** 감싼 것이 거기서 닫힌다 — 합성 글로 같은 것을 재는
    `test38_a02` 가 그 자리다."""
    assert 빈자리.보고.name == "최근.md", "① 보는 파일이 살아 있는 보고가 아니다"

    얼린것 = [f for f in (ROOT / "docs" / "review").glob("*.md")
             if f.name != "최근.md" and 자리표시자 in f.read_text(encoding="utf-8")]
    assert 얼린것, "② 그 말을 담은 얼린 판이 하나도 없다 — 이 줄이 아무것도 안 본다"


