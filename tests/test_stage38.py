def test38_b01_수용_기준이_가리킨_장이_없으면_잡는다(빈자리):
    """라) **지난 판이 밟은 그 모양이다** — 수용 기준에 O 를 찍어 두고 그
    O 가 가리키는 장이 아예 없었다(커밋 전 검토 [B]). 첫째 규칙은 그것을
    못 본다: 빈 자리가 아니라 **없는 자리**라서다.

    본다 — ① 온전한 판이 초록인가 ② 가리킨 장을 없애면 잡는가
    ③ **가리킨 절**도 같은가 ④ 몇 줄인지 말하는가."""
    assert 빈자리.본다(기준판) == [], f"① 온전한 판이 빨갛다: {빈자리.본다(기준판)}"

    장없앰 = 기준판.replace("# 3. 무엇을 했나", "# 4. 무엇을 했나")
    탈 = 빈자리.본다(장없앰)
    assert len(탈) == 1 and "3장" in 탈[0], f"② 없는 장을 놓쳤다: {탈}"
    assert 탈[0].split("줄:")[0].isdigit(), f"④ 몇 줄인지 안 말한다: {탈}"

    절없앰 = 기준판.replace("## 3-1. 첫째", "## 3-2. 첫째")
    탈2 = 빈자리.본다(절없앰)
    assert len(탈2) == 1 and "3-1" in 탈2[0], f"③ 없는 절을 놓쳤다: {탈2}"


def test38_b02_수용_기준_표_밖은_안_본다(빈자리):
    """마) **경계를 시험이 지킨다.** 대조 표에도 「11장」 이 있는데 그 장은
    이 판에 없다 — 그런데도 초록이어야 한다(b01 의 ① 이 그것을 이미 밟는다).
    넓히면 판정 칸의 문장 속 수까지 장 번호로 읽힌다.

    본다 — ① 그 줄이 실제로 그 판에 있는가 — 없으면 이 시험은 아무것도
    안 본다 ② 그런데도 초록인가 ③ **같은 말을 수용 기준 표로 옮기면**
    잡는가 — 안 잡으면 ② 가 「원래 아무것도 안 본다」 는 뜻이다."""
    assert "**했다** — 11장" in 기준판, "① 대조 표의 그 줄이 없다"
    assert 빈자리.본다(기준판) == [], "② 대조 표의 11장을 잡았다"

    옮김 = 기준판.replace("| 다) 이름으로 잰다 | `test99_a01` | O |",
                        "| 다) 이름으로 잰다 | 11장 | O |")
    탈 = 빈자리.본다(옮김)
    assert len(탈) == 1 and "11장" in 탈[0], f"③ 수용 기준 표에서도 못 잡는다: {탈}"


def test38_b03_날짜를_절_번호로_안_읽고_소제목에서_안_꺼진다(빈자리):
    """마) **넓힌 규칙이 멀쩡한 글을 잡거나, 반대로 말없이 꺼지면 안 된다.**
    셋 다 이 판이 실제로 밟은 자리다(뒤의 둘은 커밋 전 검토가 짚었다).

    본다 — ① 날짜 칸을 절 번호로 읽는가(읽으면 안 된다) ② **수용 기준 장
    안에 소제목이 있어도** 그 아래 표를 보는가 ③ 수용 기준을 **절**로 둔
    판도 보는가. ②③ 은 안 보면 검사가 말없이 아무것도 안 보는 자리다."""
    날짜칸 = "| 라) 언제 쟀나 | 2026-09-09 20:17:04 | O |"
    날짜든판 = 기준판.replace("| 다) 이름으로 잰다 | `test99_a01` | O |",
                          "| 다) 이름으로 잰다 | `test99_a01` | O |" + NL + 날짜칸)
    assert 날짜칸 in 날짜든판, "① 날짜 칸이 안 들어갔다"
    assert 빈자리.본다(날짜든판) == [], f"① 날짜를 절 번호로 읽었다: {빈자리.본다(날짜든판)}"

    나쁜줄 = "| 가) 무언가를 쟀다 | 99장 | O |"
    소제목판 = 기준판.replace("| 기준 | 어디서 잰다 | 통과 |",
                          "## 7-1. 덧붙임" + NL + NL + "| 기준 | 어디서 잰다 | 통과 |")
    탈2 = 빈자리.본다(소제목판.replace("| 가) 무언가를 쟀다 | 3장 | O |", 나쁜줄))
    assert len(탈2) == 1 and "99장" in 탈2[0], f"② 소제목 뒤에서 검사가 꺼졌다: {탈2}"

    절로둔판 = 기준판.replace("# 7. 수용 기준", "## 6-2. 수용 기준")
    탈3 = 빈자리.본다(절로둔판.replace("| 가) 무언가를 쟀다 | 3장 | O |", 나쁜줄))
    assert len(탈3) == 1 and "99장" in 탈3[0], f"③ 절로 둔 수용 기준을 안 봤다: {탈3}"
