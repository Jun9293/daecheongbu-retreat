from __future__ import annotations

import importlib.util
import pathlib

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
# 시험 자신이 찾는 말을 담아야 심을 수 있다. 글자로 박지 않고 검사가 쓰는
# 정규식에서 하나 지어낸다 — 검사가 찾는 말이 바뀌면 이 시험도 따라 바뀐다
NL = chr(10)
자리표시자 = "PLACE" + "HOLDER"


def _스크립트(이름: str):
    spec = importlib.util.spec_from_file_location(이름, ROOT / f"scripts/{이름}.py")
    모듈 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(모듈)
    return 모듈


@pytest.fixture
def 빈자리():
    return _스크립트("check_placeholder")


온전한판 = """사람이 할 것
노트북에서 직접: 없음
관리자 권한: 없음
정할 것: 없음
막혀서 못 한 것: 없음

작성 시각: 2026-09-12 (KST)
커밋: 1234abc

# 8. 검사와 시험

    1417 passed
"""


def test38_a01_심은_판은_빨갛고_안_심은_판은_초록이다(빈자리):
    """가) **둘을 같은 판에서 본다.** 안 심은 판이 빨가면 「늘 빨간 검사」 이고
    심은 판이 초록이면 「아무것도 안 보는 검사」 다 — 둘 다 검사가 아니다.

    본다 — ① 온전한 판이 초록인가 ② 값 자리에 심으면 잡는가
    ③ 이름이 앞에 붙은 꼴(`커밋: XXX_…`)도 잡는가 ④ **몇 줄인지 말하는가** —
    잡았다는 말만 하고 자리를 안 알려 주면 사람이 다시 찾아야 한다."""
    assert 빈자리.본다(온전한판) == [], "① 온전한 판이 빨갛다"

    심은판 = 온전한판.replace("1417 passed", 자리표시자)
    탈 = 빈자리.본다(심은판)
    assert 탈, "② 심었는데 초록이다"
    assert any(":" in 말 and 자리표시자 in 말 for 말 in 탈), f"④ 자리를 안 알려 준다: {탈}"

    앞에붙은판 = 온전한판.replace("1234abc", "COMMIT_" + 자리표시자)
    assert 빈자리.본다(앞에붙은판), "③ 이름이 앞에 붙은 꼴을 놓친다"


def test38_a02_검토자_원문_안에_있으면_안_잡는다(빈자리):
    """나) 검토자가 「여기가 아직 빈 자리다」 라고 짚으려면 **그 말을 써야**
    하고, 구현자가 다 채운 뒤에도 그 문장은 원문 그대로 남는다(11-3 이
    「원문을 그대로 싣는다」 고 정했다). 안 빼면 **고친 판이 빨갛다.**

    본다 — ① 원문 덩어리 안이면 넘어가는가 ② **덩어리가 끝난 뒤는 다시
    보는가** — 끝 표시를 안 보면 보고의 나머지가 통째로 검사 밖이 된다."""
    원문낀판 = 온전한판 + f"""
━━━ 검토자 여기부터 ━━━ 범위 1234abc..5678def
[고1] 8장이 아직 {자리표시자} 입니다.
━━━ 검토자 여기까지 ━━━

## 무엇을 했나
채웠습니다.
"""
    assert 빈자리.본다(원문낀판) == [], f"① 원문 안을 잡는다: {빈자리.본다(원문낀판)}"

    뒤에도있는판 = 원문낀판.replace("채웠습니다.", 자리표시자)
    assert 빈자리.본다(뒤에도있는판), "② 원문이 끝난 뒤를 안 본다"


