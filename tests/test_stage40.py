def test40_a01_표가_없거나_비거나_판정이_어긋나면_빨갛다(대조):
    """가·나) **넷을 같은 판에서 봅니다** — 온전한 판 · 표가 없는 판 ·
    표가 빈 판 · 판정이 셋 밖인 판. 온전한 판이 없으면 「늘 빨간 검사」 이고,
    나머지 셋이 없으면 「늘 초록인 검사」 입니다. 둘 다 아무것도 안 보는
    검사입니다(11-3 ③).

    봅니다 — ① 온전한 판이 초록인가 ② 표를 여는 머리가 없으면 잡는가
    ③ 머리는 있는데 **항목 줄이 하나도 없으면** 잡는가 ④ 판정이 셋 밖이면
    잡는가 — 「거의 했다」 는 「했다」 로 읽히고, 그 자리가 정확히 안 한 것을
    숨기는 자리입니다.
    """
    assert 대조.본다(온전한판) == [], f"① 온전한 판이 빨갛다: {대조.본다(온전한판)}"

    머리없는판 = 온전한판.replace("# 9. 지시문 대조", "# 9. 판단이 갈린 자리")
    assert 대조.본다(머리없는판), "② 표가 없는데 초록이다"

    빈판 = "\n".join(줄 for 줄 in 온전한판.splitlines()
                    if not 줄.startswith("| 1-a") and not 줄.startswith("| 2 ")
                    and not 줄.startswith("| 3-b"))
    assert 대조.본다(빈판), "③ 표가 비었는데 초록이다"

    어긋난판 = 온전한판.replace("**안 했다** — 왜 안 했는지", "거의 다 했다")
    탈 = 대조.본다(어긋난판)
    assert 탈 and "3-b" in 탈[0], f"④ 판정이 셋 밖인데 초록이다: {탈}"


def test40_a02_수용_기준_표를_지시문_대조로_읽지_않는다(대조):
    """가) **둘은 다른 표입니다**(11-3) — 수용 기준은 「무엇을 쟀나」 이고
    대조는 「시킨 것을 다 했나」 입니다. 수용 기준 표의 줄을 대조로 세면
    **표가 없는 판이 초록**이 됩니다.

    봅니다 — ① 대조 머리를 지웠을 때, 수용 기준 표가 그대로 있어도 빨간가
    ② 그 판에 수용 기준 표가 실제로 있는가 — 없으면 ① 이 아무것도 안 봅니다.
    """
    머리없는판 = 온전한판.replace("# 9. 지시문 대조", "# 9. 판단이 갈린 자리")
    assert "| 기준 | 어디서 잰다 | 통과 |" in 머리없는판, "② 수용 기준 표가 없다"
    assert 대조.본다(머리없는판), "① 수용 기준 표를 대조로 읽었다"


def test40_a03_다음_머리에서_멈춘다(대조):
    """가) 표는 **그 머리 아래**만 봅니다. 안 멈추면 뒤쪽 장의 표까지 끌어와
    「항목 줄이 있다」 가 되고, **대조 표가 비어도 초록**이 됩니다.

    봅니다 — ① 대조 표를 비우고 **그 뒤 장에** 같은 꼴의 줄을 두면 빨간가
    ② 그 줄이 실제로 그 판에 있는가 — 없으면 ① 이 아무것도 안 봅니다.
    """
    뒤에만있는판 = "\n".join(
        줄 for 줄 in 온전한판.splitlines()
        if not (줄.startswith("| 1-a") or 줄.startswith("| 2 ") or 줄.startswith("| 3-b"))
    ).replace("# 10. 바뀐 파일", "# 10. 바뀐 파일\n\n| 1-a | 뒤쪽 장의 줄 | 했다 |")
    assert "| 1-a | 뒤쪽 장의 줄 | 했다 |" in 뒤에만있는판, "② 그 줄이 없다"
    assert 대조.본다(뒤에만있는판), "① 다음 머리에서 안 멈췄다"


def test40_a04_머리가_둘이면_둘_다_본다(대조):
    """가) **표를 놓기 전에 같은 말로 한 장을 먼저 쓸 수 있습니다** — 실제로
    이 판의 보고가 그랬습니다(2장이 그 얘기를 하고 9장이 표입니다). 앞엣것에서
    멈추면 **표가 있는데도 「비었다」** 가 나고, 그 빨강은 고장이 아닙니다.

    봅니다 — ① 앞에 같은 말의 빈 장이 있어도 뒤의 표를 찾는가
    ② 그 빈 장이 실제로 그 판에 있는가 — 없으면 ① 이 아무것도 안 봅니다
    ③ **둘 다 비면** 여전히 잡는가.
    """
    앞장있는판 = 온전한판.replace(
        "# 7. 수용 기준", "# 2. 지시문 대조 (이 장에는 표가 없습니다)\n\n# 7. 수용 기준")
    assert 앞장있는판.count("지시문 대조") == 2, "② 같은 말의 머리가 둘이 아니다"
    assert 대조.본다(앞장있는판) == [], f"① 앞엣것에서 멈췄다: {대조.본다(앞장있는판)}"

    둘다빈판 = 앞장있는판.replace("# 9. 지시문 대조", "# 9. 판단이 갈린 자리")
    assert 대조.본다(둘다빈판), "③ 둘 다 비었는데 초록이다"


def test40_a05_한_장에_표가_둘이면_판정이_든_쪽만_본다(대조):
    """가) **같은 장에 다른 표가 있을 수 있습니다** — 실제로 이 판의 보고가
    그렇습니다(「무엇을 보나 / 못 보나」 표와 대조 표). 전부 대조 표로 보면
    **그 표들까지 판정을 달라고** 하게 되고, 그건 검사가 글 모양을 정하는
    것입니다.

    봅니다 — ① 판정 없는 표가 같은 장에 있어도 초록인가 ② 그 표가 실제로
    그 판에 있는가 — 없으면 ① 이 아무것도 안 봅니다 ③ **대조 표 안의 줄이
    판정을 빠뜨리면** 여전히 잡는가 — 넓힌 것이 구멍이 되지 않았나.
    """
    곁표 = ("| 본다 | 못 본다 |\n|---|---|\n| 표가 있나 | 번호가 맞나 |\n\n")
    둘인판 = 온전한판.replace("| 항목 | 무엇을 시켰나 | 어떻게 |", 곁표 + "| 항목 | 무엇을 시켰나 | 어떻게 |")
    assert "| 표가 있나 | 번호가 맞나 |" in 둘인판, "② 곁표가 없다"
    assert 대조.본다(둘인판) == [], f"① 곁표에 판정을 달라고 한다: {대조.본다(둘인판)}"

    빠뜨린판 = 둘인판.replace("| 2 | 저것을 하라 | **다르게 했다** — 까닭은 |",
                          "| 2 | 저것을 하라 | 나중에 적음 |")
    탈 = 대조.본다(빠뜨린판)
    assert 탈 and "'2'" in 탈[0], f"③ 대조 표 안의 빠진 판정을 놓쳤다: {탈}"


