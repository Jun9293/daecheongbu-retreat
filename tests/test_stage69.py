def test69_c03_문_넷을_다_지나야_보낸다():
    """**「확인된 때만 보낸다」 이지 「아닌 것이 확인될 때만 안 보낸다」 가
    아니다** — 못 읽는 자리가 생겨도 조용히 보내는 쪽으로 기울지 않는다
    (10장의 개발 서버 판정과 같은 방향)."""
    보냄 = 창글.index("$ws.SendKeys($키)")
    막힘 = 창글.index("$막힘 = @()")
    assert 막힘 < 보냄, "막는 검사가 보내는 자리보다 뒤에 있다"
    문 = 창글[막힘:보냄]
    assert "$허용키 -notcontains $키" in 문, "허용 목록을 안 본다"
    assert "-not $맞나" in 문, "그 창이 앞에 왔는지 안 본다"
    assert "$제목조각" in 문, "제목을 안 본다"
    assert "$허용주소" in 문, "주소를 안 본다"   # 꼴은 f02 가 따로 잰다
    # 하나라도 걸리면 **아무것도 안 보내고** 끝난다
    assert re.search(r"if \(\$막힘\.Count -gt 0\) \{[^}]*return", 문, re.S), 문


