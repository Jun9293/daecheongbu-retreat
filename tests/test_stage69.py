def test69_a01_완료_접힘은_뒷정리보다도_먼저_잰다():
    """**뒷정리도 누르는 일이다** — `Drawer.close()` 가 `안에펼침` 을 바꾼다.
    그래서 그보다도 앞에서 재야 「첫 화면」 이 참이다."""
    잰자리 = 점검JS.index("const 첫완료접힘")
    뒷정리자리 = 점검JS.index("const 시작뒷정리 = await 뒷정리()")
    assert 잰자리 < 뒷정리자리, "뒷정리가 먼저 돌아 값이 오염된다"


def test69_a02_그_항목이_다시_재지_않는다():
    """다시 재면 **점검이 이미 열어 둔 행**을 보게 되고, 그때 `open` 과
    `안에펼침` 이 함께 참이 되어 고장이 정상과 구별되지 않는다 — ⑨ 가
    앞 판까지 놓침이던 까닭이다(봐둘것 BI-i)."""
    # **주석이 아니라 재는 줄을 짚는다** — 같은 말이 그 위 주석에도 있어서
    # 그것을 잡으면 창이 엉뚱한 데를 본다(이 시험이 처음에 그랬다)
    at = 점검JS.index("완료는 기본 접힘 (첫 화면")
    몸 = 점검JS[at - 900:at + 400]
    assert "첫완료접힘" in 몸, "들고 온 값을 안 쓴다"
    # 그 자리에서 `.lslot` 을 다시 묻지 않는다
    쟀던곳 = 점검JS[점검JS.index("const 첫완료접힘"):점검JS.index("const 시작뒷정리")]
    assert ".lslot" in 쟀던곳, "첫 화면에서 재는 값이 그 값이 아니다"
    assert ".lslot" not in 몸, "그 항목이 그 자리에서 다시 잰다"


