def _고장들() -> str:
    return 점검JS[점검JS.index("const 고장들"):점검JS.index("const 뒷정리")]


def test69_b01_뒷정리를_재는_갈래_둘이_있다():
    """**이것이 없으면 누가 `뒷정리` 의 닫는 줄을 지워도 자가시험이
    조용히 초록이다** — 앞 판이 손으로만 만들어 재고 남기지 않아 실제로
    그 상태였다(11-3 의 「심기를 남기지 않으면 다음 입구는 못 잡는다」)."""
    자리 = _고장들()
    끝상태들 = re.findall(r"끝상태:\s*'([^']+)'", 자리)
    assert sorted(끝상태들) == ["뒷정리실패", "안빨감"], 끝상태들


def test69_b02_둘은_판정도_따로다():
    """한쪽만 읽으면 다른 쪽은 **늘 놓침**이 된다 — 심는 쪽이 아니라
    재는 쪽이 틀린 것인데 표에는 똑같이 「놓침」 으로 찍힌다."""
    자리 = 점검JS[점검JS.index("const 자가시험"):]
    판정 = 자리[자리.index("const 잡혔나"):자리.index("if (!잡혔나)")]
    assert "'안빨감'" in 판정 and "'뒷정리실패'" in 판정, 판정
    # ㉠ 은 **빨갛지 않고 뒷정리도 깨끗한 것**이 정답이다
    assert "!뒷정리탈.length" in 판정, "㉠ 이 뒷정리 결과를 안 본다"
    # ㉢ 은 **뒷정리가 못 닫는 것**이 정답이다
    assert "뒷정리탈.length > 0" in 판정, "㉢ 이 뒷정리 실패를 안 본다"


