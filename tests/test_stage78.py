# 2026-10-07 에 사람이 정한 값이다. **부록에는 걸지 않는다** — 세션에 저절로
# 실리는 것은 CLAUDE.md 뿐이다. **정본은 CLAUDE.md 머리말**이고 여기는 그 값을
# 옮겨 적은 것이라, 아래 시험이 둘이 같은지를 함께 잰다(한쪽만 고치면 빨개진다)
한도 = 150_000


def test78_b01_기준_문서가_한도를_안_넘는다():
    """CLAUDE.md 는 252,039자까지 자란 뒤에야 나눴다. 재는 자리가 없으면
    다음에도 넘은 뒤에 안다. **파이썬 `len` 으로 잰다**(머리말이 그렇게 적었다)."""
    글 = 기준문서.본문.read_text(encoding="utf-8")
    # **아무것도 안 보는 것은 통과가 아니다** — 빈 파일은 한도 아래다
    assert 글.startswith("# CLAUDE.md"), "CLAUDE.md 를 못 읽었다"
    머리말 = 글[:글.index("## 0. 목적과 판단 기준")]
    assert f"한도({한도:,}자" in 머리말, "머리말이 적은 한도와 이 시험의 한도가 다르다 — 머리말이 정본이다"
    글자수 = len(글)
    assert 글자수 <= 한도, (
        f"CLAUDE.md 가 {글자수:,}자다 — 한도 {한도:,}자를 {글자수 - 한도:,}자 넘었다. "
        "장 본문을 docs/CLAUDE-부록/ 으로 옮긴다"
        "(장 번호와 머리는 남기고 본문만 · 11-3 0단계의 표에 한 줄을 더한다)")


# ════════════════════════════════════════════════════════════════════
# 옮긴 자리의 한 줄 — 가리키는 문서가 실제로 있는가
# ════════════════════════════════════════════════════════════════════

# 지시문이 정한 글자다(2026-10-07). 경로에 백틱이 없어 `check_named` 가 안 본다 —
# 그래서 여기서 본다
한줄꼴 = re.compile(
    r"^본문은 docs/CLAUDE-부록/(?P<이름>[^\s`]+\.md) 에 있다\. "
    r"이 장이 걸리는 작업을 하기 전에 읽는다\.$")


def 옮긴자리() -> list[tuple[str, str, int]]:
    """CLAUDE.md 에서 (그 줄 위의 머리, 가리키는 문서 이름, 줄 번호)."""
    줄들 = 기준문서.본문.read_text(encoding="utf-8").split("\n")
    나온것 = []
    for 번호, 줄 in enumerate(줄들):
        m = 한줄꼴.match(줄)
        if not m:
            continue
        위 = next((x for x in reversed(줄들[:번호]) if x.strip()), "")
        나온것.append((위, m.group("이름"), 번호 + 1))
    return 나온것


def test78_c01_옮긴_자리의_한_줄이_있는_문서를_가리킨다():
    """부록 이름을 바꾸면 0단계 표는 `a01` 이 잡는데 **이 줄들은 옛 이름인 채
    초록**이었다(2026-10-07 커밋 전 검토). 「한 곳을 고치고 옮겨 적은 다른 곳이
    남는」 모양이다.

    넷을 잰다 — 가리키는 문서가 있다 · **그 줄 바로 위가 머리이고 같은 머리가
    그 문서에 있다**(같은 절 번호 · 같은 절 머리라는 약속) · **옮긴 머리마다
    가리키는 줄이 있다** · 꼴이 어긋난 줄이 없다.

    **셋째는 「부록마다 하나」 로는 모자란다**(커밋 전 검토 [가]) — 11-2 는 네 줄이
    한 문서를 가리켜, 한 줄이 사라지거나 어긋나도 남은 셋이 그 문서를 가리키면
    초록이었다. 그래서 머리로 센다: 장 머리(`## `)를 가리키면 장을 통째로 옮긴
    것이라 그 하나면 되고, 아니면 **그 문서의 절 머리(`### `) 전부**를 가리켜야 한다.

    **줄 수를 박지 않는다**(10장) — 장을 하나 더 옮기면 늘어난다.
    """
    자리 = 옮긴자리()
    assert 자리, "옮긴 자리의 한 줄을 하나도 못 찾았다 — 글자가 바뀌었나"
    폴더 = {p.name: p.read_text(encoding="utf-8") for p in 기준문서.부록들()}
    for 머리, 이름, 번호 in 자리:
        assert 이름 in 폴더, f"CLAUDE.md {번호}줄이 없는 문서를 가리킨다: {이름}"
        assert re.match(r"#{2,3} ", 머리), f"CLAUDE.md {번호}줄 바로 위가 머리가 아니다: {머리[:40]}"
        assert f"\n{머리}\n" in 폴더[이름], f"{이름} 에 같은 머리가 없다: {머리}"
    for 이름, 부록글 in 폴더.items():
        가리킨 = {머리 for 머리, 문서, _ in 자리 if 문서 == 이름}
        # 코드 울타리 안의 `## ` 줄(셸 주석 같은 것)은 머리가 아니다
        울타리밖 = re.sub(r"```[\s\S]*?```", "", 부록글)
        장머리 = re.findall(r"^## .+$", 울타리밖, re.M)
        assert len(장머리) == 1, f"{이름} 의 장 머리가 하나가 아니다: {장머리}"
        if 장머리[0] in 가리킨:
            바라는 = {장머리[0]}                       # 장을 통째로 옮겼다
        else:
            바라는 = set(re.findall(r"^### .+$", 울타리밖, re.M))
            assert 바라는, f"{이름} 은 장 머리도 절 머리도 안 가리켜진다"
        assert 가리킨 == 바라는, (
            f"{이름} — 가리키는 줄이 없는 머리: {sorted(바라는 - 가리킨)} · "
            f"부록에 없는 머리를 가리킴: {sorted(가리킨 - 바라는)}")
    # 꼴이 조금 어긋난 줄은 위의 정규식에서 빠져 **안 보인 채로 초록**이 된다.
    # **앞머리가 어긋난 것까지 본다** — 앞의 빈칸 · 낱말 사이 빈칸 둘 · 백틱.
    # (파일 이름으로 바로 이어지는 것만 센다 — 0단계의 설명 문장은 폴더에서 끝난다)
    글 = 기준문서.본문.read_text(encoding="utf-8")
    비슷한줄 = [x for x in 글.split("\n") if re.search(r"본문은\s+`?docs/CLAUDE-부록/[^`\s]", x)]
    assert len(비슷한줄) == len(자리), "꼴이 어긋난 한 줄이 있다 — 글자를 지시문대로 맞춘다"
