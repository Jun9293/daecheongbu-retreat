def test19_n02_목업_수를_글로_박지_않는다():
    """0장이 「HTML 4개」 라고 적어 두었는데 폴더에는 다섯이었고, 표에도
    하나가 빠져 있었다. 수를 지우고 표가 목록이 되게 했다."""
    문서 = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    머리 = 문서[:문서.index("## 0. 목적과 판단 기준")]
    assert "HTML 4개" not in 머리
    파일들 = sorted(p.name for p in (ROOT / "docs" / "mockups").glob("*.html"))
    # ③ **본 것이 0 이면 실패다.** 폴더가 옮겨 가면 빠진것도 비어 초록이다
    assert 파일들, "목업을 하나도 못 찾았다 — 폴더가 옮겨 갔나"
    빠진것 = [이름 for 이름 in 파일들 if f"`{이름}`" not in 머리]
    assert 빠진것 == [], f"표에 없는 목업이 있다: {빠진것}"
