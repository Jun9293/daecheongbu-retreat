"""고장을 심어서 검사를 검사하기 (+ 꼬리 끊기).

「못 쟀음」 이 진짜 회귀를 숨기고 있던 것을 지난 판이 **손으로** 심어서
잡았다. 그런데 그 심기를 남기지 않으면 **다음 입구는 못 잡는다** — 그래서
점검 스크립트가 갈래마다 고장을 하나씩 심었다 걷어내며 그것이 ✗ 로
나오는지 스스로 잰다.

**이 파일은 낱말을 잰다.** 점검 스크립트는 브라우저에서만 돌기 때문에,
여기서는 그것이 **어떤 모양으로 적혀 있는지**를 본다 — 실제로 심은 고장이
✗ 로 나오는지는 브라우저에서 돌려 봤고 결과는 `docs/review/최근.md` 에 있다.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
점검 = ROOT / "docs" / "checks" / "drawer.js"
SCRIPTS = ROOT / "scripts"

한계문장 = "빈 자리는 막고 거짓은 사람이 본다"


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _코드() -> str:
    """주석을 걷어낸 점검 스크립트 — 글자를 찾는 시험의 그 함정 (10장)."""
    글 = 점검.read_text(encoding="utf-8")
    글 = re.sub(r"/\*[\s\S]*?\*/", "", 글)
    return re.sub(r"(?<!:)//[^\n]*", "", 글)


