def test68_b01_드로어를_지켜보는_자리가_있다():
    """`줄을지켜본다` 는 **그 노드 자신**을 지켜보므로 노드가 갈리면 같이
    사라진다. `#statseg` 가 그랬다 — 열 때마다 새 노드라 한 번만 심으면
    여는 순간 고장이 없던 일이 된다(3 → 2 → 3 으로 재어 확인했다)."""
    at = 점검JS.index("const 드로어를지켜본다")
    몸 = 점검JS[at:at + 400]
    assert "getElementById('drawer')" in 몸, "바뀌지 않는 바깥을 안 지켜본다"
    assert "MutationObserver" in 몸 and "subtree: true" in 몸, 몸


def test68_b02_statseg_를_건드리는_갈래는_지켜보며_심는다():
    """⑰ 과 ⑱ 은 같은 자리다 — 둘 다 `#statseg` 안의 노드를 손보는데,
    그 노드는 드로어를 열 때마다 새로 그려진다."""
    for 이름 in ("⑰ 상태가 세 칸이 아님", "⑱ 켠 칸이 둘"):
        at = 점검JS.index(f"갈래: '{이름}'")
        몸 = 점검JS[at:점검JS.index("}},", at)]
        assert "드로어를지켜본다" in 몸, f"{이름} 이 한 번만 심는다"


def test68_b03_걷을_때_원래대로_되돌린다():
    """⑲ 는 타이머만 껐고 **펼친 채로 남겼다** — 그러면 그다음 판이 전부
    빨개지고 맨 끝 판이 그것을 「걷히지 않은 고장」 으로 잡는다
    (2026-09-24 에 실제로 그랬다)."""
    at = 점검JS.index("갈래: '⑲ 진단이 처음부터 펼쳐져 있음'")
    몸 = 점검JS[at:점검JS.index("}},", at)]
    assert "const 원래 = " in 몸, "원래 값을 안 기억한다"
    assert "지금.hidden = 원래" in 몸, "걷을 때 안 되돌린다"
    # **심는 쪽도 판마다 다시 찾아야 한다** — 처음 잡은 노드를 붙들면
    # 드로어를 다시 그릴 때 심은 것이 스스로 죽는다(⑰·⑱ 이 그 자리였다).
    # 글자 하나를 잠그지 않는다 — 앞선 판이 `const 원래 = 몸.hidden;` 을
    # 그대로 잠가서, 그 줄을 고치자 시험만 빨개졌다(커밋 전 검토)
    타이머 = 몸[몸.index("setInterval"):]
    assert "getElementById('dgB')" in 타이머[:200], "타이머가 처음 잡은 노드를 붙든다"


