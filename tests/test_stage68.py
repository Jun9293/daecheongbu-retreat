ROOT = pathlib.Path(__file__).resolve().parents[1]
점검JS = (ROOT / "docs" / "checks" / "drawer.js").read_text(encoding="utf-8")


# ── 가. 갈래 사이의 뒷정리 ────────────────────────────────────────────

def test68_a01_갈래마다_걷어낸_뒤에_닫는다():
    """**걷어내기가 먼저다.** 고장이 살아 있는 채로 닫으려 하면 그 고장이
    닫는 누름까지 막는다 — ⑧(상태 칸 클릭 막기)이 그 꼴이다."""
    at = 점검JS.index("try { 판 = await 점검({멈춤}); } finally { 걷어낸다(); }")
    토막 = 점검JS[at:at + 400]
    assert "뒷정리()" in 토막, 토막
    assert 토막.index("걷어낸다()") < 토막.index("뒷정리()"), "걷어내기보다 먼저 닫는다"


def test68_a02_맨_처음_판_앞에서도_닫는다():
    """사람이 드로어를 열어 둔 채 붙여넣으면 **맨 처음 판이 그것 때문에
    죽는다** — 점검은 `opener.click()` 을 조건 없이 누르고, 목록에서는
    그 누름이 이미 열린 행을 **접는다.**"""
    assert "const 시작뒷정리 = await 뒷정리();" in 점검JS
    assert 점검JS.index("const 시작뒷정리") < 점검JS.index("const 깨끗 = await 점검();")


def test68_a03_닫혔는지_재고_못_닫으면_남긴다():
    """**조용히 넘어가면 다음 판의 빨강이 무엇 탓인지 못 가른다.**
    닫는 것으로 끝내지 않고 **닫혔는지 보고** 남은 것을 돌려준다."""
    at = 점검JS.index("const 뒷정리 = async () => {")
    몸 = 점검JS[at:점검JS.index("const 자가시험", at)]
    for 이름 in ("드로어", "상태·담당자 메뉴", "기간 달력", "선행 고르기", "논의 편집창"):
        assert 이름 in 몸, f"{이름} 을 안 본다"
    assert "return 남;" in 몸, "못 닫은 것을 안 돌려준다"


def test68_a04_뒷정리_실패는_무효와_따로_적힌다():
    """**「걷히지 않은 고장」 과 뭉치면 엉뚱한 데를 판다** — 사람이 할
    일이 다르다(심기·걷기를 보는 것과 뒷정리를 보는 것).

    그리고 **0 이어도 낸다** — 빈 것과 「안 봤다」 가 갈려야 한다."""
    assert "const 뒷정리탓 = 뒷정리못함.length > 0;" in 점검JS
    at = 점검JS.index("무효: 다걷혔나 ? undefined")
    토막 = 점검JS[at:at + 400]
    assert "앞 갈래 뒷정리 실패" in 토막, 토막
    assert "걷히지 않은 고장" in 토막, 토막
    assert re.search(r"\n\s*뒷정리못함,", 토막), "못 닫은 것을 나온것에 안 싣는다"


