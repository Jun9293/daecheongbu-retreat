"""1단계 마감 판 — BI-m · BI-i · 두 계정 (CLAUDE.md 10장 · 11-3 · 봐둘것).

| 무엇 | 어디서 재나 |
|---|---|
| 갈래가 끝나면 점검이 연 것을 닫는다 | 아래 `가` |
| 못 닫은 것은 「무효」 와 따로 적는다 | 아래 `가` |
| 다시 그려도 살아남게 심는다 (⑰ · ⑱) | 아래 `나` |
| 걷을 때 원래대로 되돌린다 (⑲) | 아래 `나` |
| 사람이 정한 것이 기준 문서에 적혀 있다 | 아래 `다` |

**막는 쪽과 막히면 안 되는 쪽을 함께 잰다** (11-3). 여기 있는 것은 구조를
붙드는 자리이고, **실제로 막히는지는 브라우저에서 쟀다** — 세 화면에서
㉠(열어 둔 채 끝남 → 초록) · ㉡(안 걷힌 고장 → 빨강) · ㉢(못 닫음 →
「앞 갈래 뒷정리 실패」)을 일부러 만들어 돌렸다(보고 4장).
"""

from __future__ import annotations

import pathlib
