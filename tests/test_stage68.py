def test68_c03_인계와_봐둘것의_BI_i_갈래가_같다():
    """한쪽만 고치면 「남은 것」 표가 실제보다 작아 보이고, 그 표가 다음
    판이 이어받는 유일한 자리다.

    **갈래 목록을 여기 적지 않고 봐둘것에서 끌어온다** — 적어 두면 갈래가
    하나 늘 때 이 시험도 함께 고쳐야 하고, 안 고치면 조용히 덜 본다(10장).

    **닫힌 뒤에는 반대를 잰다** (2026-09-25). BI-i 가 「처리함」 이 되면
    「남은 것」 표에 있으면 안 된다 — 여기서도 그것을 재고(`test69_d02` 와
    겹치지만 이 시험이 스스로 서야 한다), **아직 열려 있을 때만** 갈래를
    견준다. 조건을 안 갈라 두면 닫는 판이 이 시험을 지우게 되고, 그러면
    다시 열릴 때 아무도 안 본다.
    """
    봐둘것 = (ROOT / "docs" / "봐둘것.md").read_text(encoding="utf-8")
    머리 = next(x for x in 봐둘것.splitlines() if x.startswith("### BI-i."))
    갈래들 = [c for c in 머리 if c in "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳"]
    assert len(갈래들) >= 2, f"봐둘것 BI-i 머리에서 갈래를 못 읽었다 — {머리}"

    인계 = (ROOT / "docs" / "인계.md").read_text(encoding="utf-8")
    줄들 = [x for x in 인계.splitlines() if "BI-i" in x]
    남은것표 = [x for x in 줄들 if "다음 판" in x]

    if "처리함" in 머리:
        # 닫혔으면 이어받을 것이 없다 — 그 확인은 test69_d02 가 한다
        assert not 남은것표, f"닫힌 BI-i 가 「남은 것」 표에 있다: {남은것표}"
        return

    적힌것 = " / ".join(줄들)
    for 갈래 in 갈래들:
        assert 갈래 in 적힌것, f"인계의 BI-i 줄에 {갈래} 가 없다 — {적힌것}"

    # **양쪽을 본다.** 한 방향만 보면 인계에만 있는 갈래가 안 걸리는데,
    # 이 시험의 이름과 수용 기준은 「갈래 수가 같다」 이다(커밋 전 검토).
    #
    # **되돌아보는 쪽은 「남은 것」 표 줄만 본다** — 갱신 블록은 이 판이
    # 무엇을 했는지 적는 자리라 봐둘것 머리에 없는 갈래(이 판이 재면서
    # 찾아 그 자리에서 닫은 것)가 정당하게 들어 있고, 번호 매김(①②③)
    # 까지 섞인다. **표가 실제보다 작아 보이는 것**을 막는 것이 이 시험의
    # 목적이므로 그 표 줄이 재는 자리다.
    assert 남은것표, f"인계의 「남은 것」 표에 BI-i 줄이 없다 — {적힌것}"
    표갈래 = {c for x in 남은것표 for c in x if c in "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳"}
    더한것 = 표갈래 - set(갈래들)
    assert not 더한것, f"「남은 것」 표에만 있는 갈래 — 봐둘것 BI-i 머리에 없다: {sorted(더한것)}"
