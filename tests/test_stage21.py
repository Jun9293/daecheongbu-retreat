"""자가시험을 넓히기 (+ 언제나 ✓ 인 줄 · 죽는 판).

자가시험이 **보드 한 화면**에서 돌고, 부서 리더 건너뜀 열다섯 중
**하나**만 지났다. 검사를 검사하는 도구가 좁으면 넓은 검사를 못 믿는다.

세 가지를 넓혔다 —
  · 화면에만 있는 갈래(목록의 상태 칸·완료 접힘, 달력의 비침·날짜 없는
    업무)를 그 화면에서 심는다
  · **건너뛰는 길도 심는다** — ✗ 가 아니라 `·` 가 나오는 것이 정답이다
  · 점검이 한복판에서 죽으면 **출력이 스스로 말한다**(`완주`)

**이 파일은 낱말을 잰다.** 점검 스크립트는 브라우저에서만 돌기 때문에,
실제로 심은 고장이 어떻게 나오는지는 `docs/review/최근.md` 에 있다.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
점검 = ROOT / "docs" / "checks" / "drawer.js"


def _코드() -> str:
    """주석을 걷어낸 점검 스크립트 — 글자를 찾는 시험의 그 함정 (10장)."""
    글 = 점검.read_text(encoding="utf-8")
    글 = re.sub(r"/\*[\s\S]*?\*/", "", 글)
    return re.sub(r"(?<!:)//[^\n]*", "", 글)


def _고장들(코드: str) -> str:
    return 코드[코드.index("const 고장들"):코드.index("const 자가시험")]


