# ════════════════════════════════════════════════════════════════════


# 언제나 ✓ 가 되는 자리는 **두 모양**이다. 하나만 세면 나머지가 샌다 —
# 검토가 `잰다(true, …)` 를 심어 보이면서 짚었다. 그리고 그것이 **다음에
# 생길 모양**이다: ✗ 를 찍는 길이 `잰다` 하나로 모였으므로 앞으로 줄을
# 더하는 사람은 `results.push` 가 아니라 `잰다` 를 쓴다.
언제나초록모양 = (r"results\.push\(\s*[`'\"]✓", r"잰다\(\s*(?:true|1)\s*,")

# 그 모양이지만 **반대쪽을 다른 자리가 잡고 있는** 곳 — 이유와 함께 적는다.
# 여기 없는 것이 걸리면 그 줄이 아무것도 안 재고 있다는 뜻이다.
언제나초록허용 = {
    "잰다(true, ` ${label}`);":
        "check 의 ✓ 갈래다 — 바로 위에서 주변이 무너졌으면 잰다(false) 로 빠진다",
    "results.push(`✓ ${isBoard ? '바' : isList ? '업무 이름' : '점'}"
    "을 눌러 그 자리에서 패널이 열림`);":
        "바로 위에서 안 열렸으면 치명으로 빠져나간다 — 반대쪽을 이미 잡는다",
}


def 언제나초록(코드: str) -> list[str]:
    """조건 없이 ✓ 만 찍는 줄 — 고장이 나도 ✓ 가 되는 자리."""
    return [줄.strip() for 줄 in 코드.splitlines()
            if any(re.search(무늬, 줄) for 무늬 in 언제나초록모양)]


def test21_v01_언제나_초록인_줄이_남아_있지_않다():
    """**항목 수에 들어가면서 아무것도 안 재는 줄은 만점을 만듭니다**
    (봐둘것 AJ-d). 「완료 접힘 자리 있음」 과 「날짜 없는 업무 자리」 가
    그랬다 — 있든 없든 ✓ 였다.

    **남기는 것은 이유와 함께 적습니다** — 반대쪽을 다른 자리가 잡고
    있는 곳(`언제나초록허용`)만입니다. 목록에 없는 것이 걸리면 그 줄이
    아무것도 안 재고 있다는 뜻입니다.

    **모양이 둘입니다.** `results.push('✓ …')` 과 `잰다(true, …)` —
    검토가 뒤엣것을 심어 보이면서 짚었고, ✗ 를 찍는 길이 `잰다` 하나로
    모였으므로 **뒤엣것이 다음에 생길 모양**입니다.
    """
    남은것 = 언제나초록(_코드())
    # ③ **본 것이 0 이면 실패다** — 두 모양 다 실제로 잡히는지 심어서 본다
    for 심을것 in ("    results.push('✓ 심은 줄');", "    잰다(true, ' 심은 줄');"):
        심음 = _코드() + chr(10) + 심을것
        assert len(언제나초록(심음)) == len(남은것) + 1, \
            f"이 모양을 못 잡는다: {심을것}"
    모름 = [줄 for 줄 in 남은것 if 줄 not in 언제나초록허용]
    assert 모름 == [], f"언제나 ✓ 인 줄이 이유 없이 남았다: {모름}"


