def test21_r02_갈래마다_심을_것과_기다릴_것이_짝이다():
    """갈래 수를 세어 두지 않는다 (10장) — 짝이 맞는지만 본다."""
    자리 = _고장들(_코드())
    갈래 = re.findall(r"갈래:\s*'([^']+)'", 자리)
    심는다 = re.findall(r"심는다:", 자리)
    기다림 = re.findall(r"(?:나와야|건너뜀나와야):", 자리)
    assert len(갈래) == len(심는다) == len(기다림), \
        f"갈래 {len(갈래)} · 심는다 {len(심는다)} · 기다림 {len(기다림)}"
    assert len(set(갈래)) == len(갈래), f"갈래 이름이 겹친다: {갈래}"
    assert len(갈래) >= 10, f"넓히기 전보다 갈래가 적다: {갈래}"
