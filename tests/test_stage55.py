def test55_d01_A_는_제목만으로_나지_않는다():
    """총점은 늘 제목보다 크거나 같아, 총점으로 A 를 한 번 더 거르면 아무것도 안 막는다."""
    assert 짝.등급매김(0.99, 0.99) == "A"
    assert 짝.등급매김(0.99, 0.99, ["담당"]) == "B"        # 제목이 같아도 담당이 어긋나면 사람이 본다
    assert 짝.등급매김(0.75, 0.72) == "B"
    assert 짝.등급매김(0.62, 0.60) == "C"
    맞는것 = 짝.짝짓는다([ㄴ("포스터 인쇄 발주", start="2026-06-01")],
                    [ㅇ("포스터 인쇄 발주", start="2026-06-01")])
    assert (맞는것[0].등급, 맞는것[0].어긋난칸) == ("A", ())
    # 제목이 같아도 구분 · 담당 · 시작일이 어긋나면 A 가 아니다
    for 노션쪽, 앱쪽 in ((ㄴ("포스터 인쇄 발주", kind="Sub"), ㅇ("포스터 인쇄 발주", kind="main")),
                     (ㄴ("포스터 인쇄 발주", team="4 스케치"), ㅇ("포스터 인쇄 발주", team="chongmu")),
                     (ㄴ("포스터 인쇄 발주", start="2026-06-01"), ㅇ("포스터 인쇄 발주", start="2026-08-01"))):
        p = 짝.짝짓는다([노션쪽], [앱쪽])[0]
        assert p.등급 == "B" and p.어긋난칸, (p.등급, p.어긋난칸)


