def test55_b01_점수가_높은_짝이_먼저_확정된다_입력_순서와_무관():
    """1판의 탐욕 1:1 은 앞에서 먹은 짝이 뒤의 더 맞는 짝을 밀어냈다."""
    노션 = [ㄴ("명찰 제작"), ㄴ("명찰 제작 발주")]
    앱 = [ㅇ("명찰 제작 발주"), ㅇ("명찰 제작")]
    나온것 = {p.노션: p.앱 for p in 짝.짝짓는다(노션, 앱)}
    assert 나온것 == {0: 1, 1: 0}
    # 순서를 뒤집어도 같은 답
    뒤집음 = {p.노션: p.앱 for p in 짝.짝짓는다(노션[::-1], 앱[::-1])}
    assert 뒤집음 == {0: 1, 1: 0}


def test55_b02_고장을_심으면_뒤_짝이_밀려난다(monkeypatch):
    """심는 고장 = 1판 방식(들어온 순서대로 먼저 먹기). 그러면 b01 의 답이 틀려야 한다."""
    노션 = [ㄴ("명찰 제작"), ㄴ("명찰 제작 발주")]
    앱 = [ㅇ("명찰 제작 발주"), ㅇ("명찰 제작")]

    def 순서대로(노션들, 앱들, *, 문턱=짝.닮음문턱):
        쓴앱, 나온것 = set(), []
        for i, n in enumerate(노션들):
            for j, a in enumerate(앱들):
                if j in 쓴앱:
                    continue
                총, 바탕 = 짝.점수(n, a)
                if 바탕 >= 문턱:
                    쓴앱.add(j)
                    나온것.append(짝.짝(i, j, 총, 바탕, 짝.등급매김(총, 바탕)))
                    break
        return 나온것
    monkeypatch.setattr(짝, "짝짓는다", 순서대로)
    틀린것 = {p.노션: p.앱 for p in 짝.짝짓는다(노션, 앱)}
    assert 틀린것 == {0: 0, 1: 1}, "심은 고장이 안 밟혔다 — 이 시험이 아무것도 안 잰다"


