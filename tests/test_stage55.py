def test55_d03_네갈래의_합이_맞는다():
    노션 = [ㄴ("(D-13주차)", kind=""), ㄴ("명찰 제작"), ㄴ("버스 대절"), ㄴ("포스터 인쇄")]
    앱 = [ㅇ("명찰 제작"), ㅇ("포스터 인쇄 발주"), ㅇ("식대 정산")]
    나온것 = 짝.짝짓는다(노션, 앱)
    갈래 = 짝.네갈래(노션, 앱, 나온것)
    assert 갈래["노션만"] + 갈래["둘 다 · 제목 같음"] + 갈래["둘 다 · 제목 다름"] == len(노션) - 갈래["표지(갈래 밖)"]
    assert 갈래["앱만"] + 갈래["둘 다 · 제목 같음"] + 갈래["둘 다 · 제목 다름"] == len(앱)
    assert sum(짝.등급수(나온것).values()) == len(나온것)
