def test55_d01_등급은_제목과_총점_둘_다_본다():
    assert 짝.등급매김(0.99, 0.99) == "A"
    assert 짝.등급매김(0.95, 0.80) == "B"      # 제목이 덜 닮으면 A 가 아니다
