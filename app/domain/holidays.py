"""공휴일 표 (CLAUDE.md 4-13 · 목업 E).

**표는 여기 한 곳이다** — 화면마다 세어 두면 갈린다(2장의 그 원칙). 달력이
날짜 글자를 지연색으로 칠하고 꼬리표에 이름을 다는 데 쓴다.

**표에 없는 해를 열면 조용히 비우지 않는다.** 빈 것과 「모르는 것」 이 같은
모양이면, 2029년 달력을 여는 사람은 그 해에 공휴일이 없다고 읽는다 — 4-10 이
「빠진 선행을 조용히 삼키지 않는다」 고 한 것과 같은 자리다. 그래서 `있나()` 가
따로 있고 화면이 「공휴일 표 없음」 을 한 줄 낸다.

**음력에서 오는 날(설날 · 추석 · 부처님오신날)은 사람이 확인해야 한다** — 이
창이 적어 넣은 값이고 달력을 직접 재어 본 것이 아니다. 양력으로 고정된 날
(신정 · 삼일절 · 어린이날 · 현충일 · 광복절 · 개천절 · 한글날 · 성탄절)은
해마다 같다. 대체공휴일은 **넣지 않았다** — 규칙이 해마다 바뀌고, 안 넣으면
「평일로 잘못 본다」 이지만 넣고 틀리면 「없는 휴일을 만든다」 라 더 비싸다.
"""

from __future__ import annotations

import datetime as dt

# 양력으로 고정된 날 — (월, 일): 이름
_고정 = {
    (1, 1): "신정",
    (3, 1): "삼일절",
    (5, 5): "어린이날",
    (6, 6): "현충일",
    (8, 15): "광복절",
    (10, 3): "개천절",
    (10, 9): "한글날",
    (12, 25): "성탄절",
}

# 음력에서 오는 날 — **사람이 확인할 것**(위 머리말). 설날·추석은 앞뒤 하루씩
_음력 = {
    2026: {
        (2, 16): "설 연휴", (2, 17): "설날", (2, 18): "설 연휴",
        (5, 24): "부처님오신날",
        (9, 24): "추석 연휴", (9, 25): "추석", (9, 26): "추석 연휴",
    },
    2027: {
        (2, 6): "설 연휴", (2, 7): "설날", (2, 8): "설 연휴",
        (5, 13): "부처님오신날",
        (9, 14): "추석 연휴", (9, 15): "추석", (9, 16): "추석 연휴",
    },
    2028: {
        (1, 26): "설 연휴", (1, 27): "설날", (1, 28): "설 연휴",
        (5, 2): "부처님오신날",
        (10, 2): "추석 연휴", (10, 3): "추석", (10, 4): "추석 연휴",
    },
}

아는해 = tuple(sorted(_음력))


def 있나(year: int) -> bool:
    """그 해의 표를 들고 있나 — **모르는 것과 없는 것을 가르는 자리**다."""
    return year in _음력


def 이름(day: dt.date) -> str | None:
    """그 날의 공휴일 이름. 표에 없는 해면 `None` 이다 — `있나()` 와 함께 쓴다.

    개천절과 추석이 겹치는 해가 있다(2028) — 그때는 **음력 쪽 이름**을 낸다:
    그 날 사람들이 부르는 이름이 그쪽이고, 꼬리표는 한 줄뿐이다.
    """
    if not 있나(day.year):
        return None
    열쇠 = (day.month, day.day)
    return _음력[day.year].get(열쇠) or _고정.get(열쇠)
