"""계좌번호의 꼴 — 무엇이 계좌번호로 보이는가 (CLAUDE.md 7-4 · 봐둘것 BB-c).

**아무것도 import 하지 않는다** — `app/paths.py` 와 같은 자리다. 들어올 값을 막는 판정은
`app.domain.budget.account_problem` 하나이고, 이 파일은 그 판정과 두 검사
(`scripts/check_dev_db.py` · `scripts/check_names.py`)가 **같은 꼴**을 보게 하려고만 있다 —
검사는 앱을 읽으면 폴더와 서명키를 만들므로(11-2) 이 파일만 경로로 읽는다.

꼴은 2026-09-14 시트의 계좌 64 줄을 재어 정했다 — 전부 은행 이름(한글) + 숫자 12~14 개,
숫자와 하이픈만. 실제 계좌가 막히지 않게 그보다 넓게 둔다.
"""

import re

# 숫자 개수 — 시중 계좌는 10~14, 가상계좌까지 16. 이보다 짧거나 길면 계좌번호가 아니다
숫자_최소, 숫자_최대 = 10, 16

# 칸 하나가 계좌번호 꼴인가 — 숫자로 시작해 숫자로 끝나고, 사이에 하이픈이 하나씩만
칸꼴 = re.compile(r"[0-9]+(?:-[0-9]+)*")

# 글 안에서 계좌번호로 보이는 자리 — 영숫자에 붙은 것은 안 본다(해시 · 시각 · 버전)
글속꼴 = re.compile(r"(?<![0-9A-Za-z-])[0-9]+(?:-[0-9]+)*(?![0-9A-Za-z-])")

# 날짜로 시작하는 조각(2026-09-12-… · 백업 이름의 20260915-002352) — 파일 이름에 흔하다
_날짜머리 = re.compile(r"(?:19|20)[0-9]{2}(?:-[0-9]{2}-[0-9]{2}|[0-9]{4}-[0-9]{6}(?![0-9]))")


def 숫자수(글: str) -> int:
    # isdigit 은 전각 숫자도 숫자로 본다 — 꼴은 ASCII 숫자만
    return sum(ch in "0123456789" for ch in 글)


def 계좌로보이나(조각: str) -> bool:
    """글 속 한 조각이 계좌번호로 보이나 — 검사가 쓴다.

    **빼는 것** — 날짜로 시작하는 조각 · 휴대폰 꼴(01 로 시작하는 숫자 10~11 개: 연락처는 대응표로
    따로 본다) · **지어낸 번호**(999 로 시작 · 한 숫자만 되풀이 · 1234… 처럼 이어 오르는 것: 시험·seed·
    문서가 쓰는 표시). 그 꼴의 실제 계좌는 놓친다 — ponytail: 지어낸 표시를 꼴로 가른다,
    실제로 부딪히면 넘김 목록을 둔다.
    """
    if _날짜머리.match(조각):
        return False
    숫자 = "".join(ch for ch in 조각 if ch in "0123456789")
    if not 숫자_최소 <= len(숫자) <= 숫자_최대:
        return False
    if 숫자.startswith("01") and len(숫자) <= 11:
        return False
    이어오름 = all((int(b) - int(a)) % 10 == 1 for a, b in zip(숫자, 숫자[1:]))
    return not (숫자.startswith("999") or len(set(숫자)) == 1 or 이어오름)
